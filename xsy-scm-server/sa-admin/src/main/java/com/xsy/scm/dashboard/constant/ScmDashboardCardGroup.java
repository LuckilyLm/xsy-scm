package com.xsy.scm.dashboard.constant;

/**
 * 首页 KPI 卡片的数据来源分组。
 *
 * <p>
 * 同组卡片由<b>同一次聚合</b>算出：销售额与订单数出自同一趟销售聚合，采购额与收货数出自同一趟采购聚合， 库存预警独立一趟。分组的唯一用途是让取数按「这批人实际要看哪几张卡」裁剪 ——
 * 只有库存预警权的人不该为销售与采购各付一次查询。
 *
 * <p>
 * 它与权限码不是一回事：权限码决定「能不能看」，分组决定「要看就得取哪组数」。 多张卡共用一个权限码（销售额与订单数都是 {@code scm:order:query}）， 而分组是按聚合切开的，两者维度不同，不能合并。
 */
public enum ScmDashboardCardGroup {

    /** 销售聚合：今日销售额与今日订单数。 */
    SALES,

    /** 采购聚合：今日采购额与今日收货单数。 */
    PURCHASE,

    /** 库存预警：取值是预警列表的分页总数，走独立查询。 */
    INVENTORY_WARNING
}
