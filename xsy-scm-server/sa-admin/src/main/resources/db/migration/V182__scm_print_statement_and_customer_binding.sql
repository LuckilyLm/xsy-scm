-- 一个客户对一种单据类型最多一条有效绑定：换模板走更新，解除绑定走软删。
-- 不建数据库外键：模板与客户都由各自领域维护，跨域关系在这里只做配置。
CREATE TABLE xsy_print_customer_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    document_type VARCHAR(32) NOT NULL,
    template_id BIGINT NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_scm_print_customer_template_document_type CHECK (document_type IN (
        'PURCHASE_ORDER', 'DELIVERY_NOTE', 'SORTING_TICKET', 'SALES_ORDER', 'TRACE_UNIT', 'STATEMENT'))
);

CREATE UNIQUE INDEX uk_scm_print_customer_template
    ON xsy_print_customer_template (customer_id, document_type) WHERE deleted = FALSE;

-- 按模板反查使用情况：停用或删除模板前可以知道哪些客户仍绑定它。
CREATE INDEX idx_scm_print_customer_template_template
    ON xsy_print_customer_template (document_type, template_id);
