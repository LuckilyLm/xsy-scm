-- 过账特殊单据（D-1028-16）：财务在系统里登记对外账目的虚拟单据。
--
-- 口径来自 2026-10-27 需求会：过账单据只是「这笔账在外部怎么记的」的留痕，
-- 不进正常业务流 —— 不生成应收/应付、不参与核销、不改客户余额与账龄。
-- 因此本表没有金额变动方向，也没有任何派生余额列；查询只能看到过账记录本身。
--
-- 作废不是软删除：作废是另一件事实（谁、何时、为什么），落在 xsy_finance_posting_void。
-- 过账行 append-only，反向/更正都靠追加事实，读时按「有没有作废行」推导有效状态，
-- 不落会漂移的 status 列（与抹零同一取向，ScmFinanceSchemaPgIT 的状态列禁令一致）。
--
-- 税点按纸质单据上写的数字原样保存为百分比（0–100），不据此计算税额：
-- 系统里没有发票与计税链路，算出来的税额会是一个没人核对过的第三个数。

CREATE SEQUENCE finance_posting_no_seq;

CREATE TABLE xsy_finance_posting (
    id                                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posting_no                        VARCHAR(64)   NOT NULL CHECK (btrim(posting_no) <> ''),
    customer_id                       BIGINT        NOT NULL,
    customer_name_snapshot            VARCHAR(150)  NOT NULL CHECK (btrim(customer_name_snapshot) <> ''),
    settlement_customer_id            BIGINT,
    settlement_customer_name_snapshot VARCHAR(150),
    document_date                     DATE          NOT NULL,
    amount                            NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    tax_rate                          NUMERIC(8,4)  CHECK (tax_rate IS NULL OR (tax_rate >= 0 AND tax_rate <= 100)),
    refund_status                     VARCHAR(16)   NOT NULL DEFAULT 'PENDING'
        CONSTRAINT ck_finance_posting_refund_status
            CHECK (refund_status IN ('PENDING', 'PARTIAL', 'REFUNDED')),
    remark                            VARCHAR(500),
    version                           INTEGER       NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted                           BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at                        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at                        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by                        VARCHAR(64),
    updated_by                        VARCHAR(64),
    -- 过账记录不允许软删：登记错了走作废，作废原因留给对账时的解释。
    CONSTRAINT ck_finance_posting_append_only CHECK (deleted = FALSE)
);

CREATE UNIQUE INDEX uk_finance_posting_no ON xsy_finance_posting (posting_no) WHERE deleted = FALSE;
CREATE INDEX idx_finance_posting_customer_date ON xsy_finance_posting (customer_id, document_date DESC);
CREATE INDEX idx_finance_posting_date ON xsy_finance_posting (document_date DESC);

COMMENT ON TABLE xsy_finance_posting IS '过账特殊单据；虚拟单据，不生成应收应付、不参与核销、不影响客户余额';
COMMENT ON COLUMN xsy_finance_posting.customer_id IS '过账对应的客户；名称按登记时快照保存，客户改名不改历史过账';
COMMENT ON COLUMN xsy_finance_posting.document_date IS '过账业务日期，按纸质单据填写';
COMMENT ON COLUMN xsy_finance_posting.amount IS '过账金额，必须大于 0';
COMMENT ON COLUMN xsy_finance_posting.tax_rate IS '税点百分比（0–100），按单据原样记录，不据此计算税额';
COMMENT ON COLUMN xsy_finance_posting.refund_status IS '返款状态：PENDING 未返 / PARTIAL 部分返 / REFUNDED 已返；只记录状态，不记录返款金额';

CREATE TABLE xsy_finance_posting_void (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    posting_id BIGINT       NOT NULL,
    reason     VARCHAR(500) NOT NULL CHECK (btrim(reason) <> ''),
    voided_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version    INTEGER      NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_finance_posting_void_append_only CHECK (deleted = FALSE)
);

-- 一张过账只能作废一次；重复作废由服务层与这个唯一索引双层兜底。
CREATE UNIQUE INDEX uk_finance_posting_void_posting ON xsy_finance_posting_void (posting_id)
    WHERE deleted = FALSE;

COMMENT ON TABLE xsy_finance_posting_void IS '过账作废事实；有效状态由这张表有没有对应行推导';
COMMENT ON COLUMN xsy_finance_posting_void.reason IS '作废原因，必填';

-- 财务日志放行过账动作：登记、修改、作废都要能按「过账 + id」查回整条轨迹。
ALTER TABLE xsy_finance_operation_log DROP CONSTRAINT ck_finance_operation_log_business_type;
ALTER TABLE xsy_finance_operation_log ADD CONSTRAINT ck_finance_operation_log_business_type
    CHECK (business_type IN ('RECEIVABLE', 'PAYABLE', 'RECEIPT', 'PAYMENT', 'WRITE_OFF', 'WAIVER', 'POSTING'));

ALTER TABLE xsy_finance_operation_log DROP CONSTRAINT ck_finance_operation_log_type;
ALTER TABLE xsy_finance_operation_log ADD CONSTRAINT ck_finance_operation_log_type
    CHECK (operation_type IN ('GENERATE', 'RED_GENERATE', 'RECEIVE', 'PAY',
                              'WRITE_OFF', 'WRITE_OFF_REVERSE',
                              'RECEIPT_REVERSE', 'PAYMENT_REVERSE',
                              'WAIVER_ADD', 'WAIVER_REVERSE',
                              'POSTING_ADD', 'POSTING_UPDATE', 'POSTING_VOID'));
