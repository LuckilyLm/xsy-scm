CREATE TABLE xsy_trace_inspection_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_no VARCHAR(100) NOT NULL UNIQUE,
    report_name VARCHAR(200) NOT NULL,
    lot_id BIGINT NOT NULL,
    inspection_date DATE NOT NULL,
    inspection_org VARCHAR(200) NOT NULL,
    conclusion VARCHAR(24) NOT NULL CHECK (conclusion IN ('QUALIFIED', 'UNQUALIFIED', 'UNDETERMINED')),
    expires_at TIMESTAMPTZ,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'WITHDRAWN')),
    published_by VARCHAR(100),
    published_at TIMESTAMPTZ,
    withdrawn_by VARCHAR(100),
    withdrawn_at TIMESTAMPTZ,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    operation_history JSONB NOT NULL DEFAULT '[]'::jsonb,
    CHECK (expires_at IS NULL OR (expires_at AT TIME ZONE 'Asia/Shanghai')::date >= inspection_date),
    CHECK (status = 'DRAFT' OR (published_by IS NOT NULL AND published_at IS NOT NULL)),
    CHECK (status <> 'WITHDRAWN' OR (withdrawn_by IS NOT NULL AND withdrawn_at IS NOT NULL))
);
CREATE INDEX idx_trace_inspection_report_lot ON xsy_trace_inspection_report(lot_id, id DESC);
COMMENT ON TABLE xsy_trace_inspection_report IS '批次检测报告；发布后内容冻结，撤回保留记录';
COMMENT ON COLUMN xsy_trace_inspection_report.operation_history IS '保存、发布与撤回的操作人和时间，随业务事务追加';

