-- 价格变更审计合并为一张表。
--
-- 协议价、客户类型价、客户分组价、时价各自带一张结构相同的日志表，除「指向哪张价格表」，
-- 列定义完全一致；价格历史页只能 UNION 四份查询。统一成一张表后，价格类型成为一列，
-- 新增价格维度只需扩枚举，不再复制建表与查询。
CREATE TABLE xsy_price_operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_type VARCHAR(20) NOT NULL,
    price_id BIGINT NOT NULL,
    operation_type VARCHAR(20) NOT NULL,
    operator VARCHAR(64) NOT NULL,
    before_data JSONB,
    after_data JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    CONSTRAINT ck_price_operation_log_type CHECK (price_type IN ('AGREEMENT', 'CUSTOMER_TYPE', 'CUSTOMER_GROUP', 'TIME_PRICE')),
    CONSTRAINT ck_price_operation_log_operation CHECK (operation_type IN ('CREATE', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_price_operation_log_before CHECK (before_data IS NULL OR jsonb_typeof(before_data) = 'object'),
    CONSTRAINT ck_price_operation_log_after CHECK (after_data IS NULL OR jsonb_typeof(after_data) = 'object')
);

CREATE INDEX idx_price_operation_log_price
    ON xsy_price_operation_log (price_type, price_id, created_at DESC);
CREATE INDEX idx_price_operation_log_time
    ON xsy_price_operation_log (created_at DESC);

INSERT INTO xsy_price_operation_log (price_type, price_id, operation_type, operator, before_data, after_data,
    created_at, created_by)
SELECT 'AGREEMENT', agreement_price_id, operation_type, operator, before_data, after_data, created_at, created_by
FROM xsy_customer_agreement_price_operation_log;

INSERT INTO xsy_price_operation_log (price_type, price_id, operation_type, operator, before_data, after_data,
    created_at, created_by)
SELECT 'CUSTOMER_TYPE', customer_type_price_id, operation_type, operator, before_data, after_data, created_at,
    created_by
FROM xsy_customer_type_price_operation_log;

INSERT INTO xsy_price_operation_log (price_type, price_id, operation_type, operator, before_data, after_data,
    created_at, created_by)
SELECT 'CUSTOMER_GROUP', group_price_id, operation_type, operator, before_data, after_data, created_at, created_by
FROM xsy_customer_group_price_operation_log;

INSERT INTO xsy_price_operation_log (price_type, price_id, operation_type, operator, before_data, after_data,
    created_at, created_by)
SELECT 'TIME_PRICE', time_price_id, operation_type, operator, before_data, after_data, created_at, created_by
FROM xsy_pricing_time_price_operation_log;

-- 审计日志只追加：能被改写就失去意义。
CREATE OR REPLACE FUNCTION xsy_price_operation_log_append_only() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'xsy_price_operation_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_price_operation_log_append_only
    BEFORE UPDATE OR DELETE ON xsy_price_operation_log
    FOR EACH STATEMENT EXECUTE FUNCTION xsy_price_operation_log_append_only();

DROP TRIGGER IF EXISTS trg_time_price_log_append_only ON xsy_pricing_time_price_operation_log;
DROP FUNCTION IF EXISTS xsy_time_price_log_append_only();
DROP TABLE xsy_customer_agreement_price_operation_log, xsy_customer_type_price_operation_log,
    xsy_customer_group_price_operation_log, xsy_pricing_time_price_operation_log;

COMMENT ON TABLE xsy_price_operation_log IS '价格变更审计：price_type 指明价格维度，price_id 指向该维度自己的价格表';

-- 换货关联收进退货单。
--
-- 这是 1:1 关系：一条退货最多对应一张换货单，原单就是退货单自己的 order_id，
-- 单独建表只多存一个可从退货单推出的 original_order_id。换货草稿删除时清回 NULL。
ALTER TABLE xsy_order_return ADD COLUMN replacement_order_id BIGINT;

UPDATE xsy_order_return r
SET replacement_order_id = l.replacement_order_id
FROM xsy_order_exchange_link l
WHERE l.return_id = r.id;

CREATE UNIQUE INDEX uk_order_return_replacement
    ON xsy_order_return (replacement_order_id)
    WHERE replacement_order_id IS NOT NULL;

DROP TABLE xsy_order_exchange_link;

COMMENT ON COLUMN xsy_order_return.replacement_order_id IS '换货单 ID；为空表示没有换货。换货草稿删除后清空，允许重新创建。';
