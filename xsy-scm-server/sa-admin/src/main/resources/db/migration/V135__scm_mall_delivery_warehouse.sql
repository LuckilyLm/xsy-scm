-- 商城配送仓：客户绑定优先；未绑定时按收货地址区县匹配管理员维护的配送仓。
ALTER TABLE xsy_customer ADD COLUMN mall_delivery_warehouse_id BIGINT;
ALTER TABLE xsy_sales_order ADD COLUMN mall_delivery_warehouse_id BIGINT;

CREATE TABLE xsy_mall_district_warehouse (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_code INTEGER NOT NULL CHECK (district_code > 0),
    warehouse_id BIGINT NOT NULL CHECK (warehouse_id > 0),
    priority INTEGER NOT NULL DEFAULT 0 CHECK (priority >= 0),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    updated_by VARCHAR(64) NOT NULL
);

CREATE UNIQUE INDEX uk_mall_district_warehouse_active
    ON xsy_mall_district_warehouse(district_code, warehouse_id) WHERE deleted = FALSE;
CREATE INDEX idx_mall_district_warehouse_priority
    ON xsy_mall_district_warehouse(district_code, priority, id) WHERE deleted = FALSE;
CREATE INDEX idx_customer_mall_delivery_warehouse
    ON xsy_customer(mall_delivery_warehouse_id) WHERE deleted = FALSE AND mall_delivery_warehouse_id IS NOT NULL;
CREATE INDEX idx_sales_order_mall_delivery_warehouse
    ON xsy_sales_order(mall_delivery_warehouse_id) WHERE deleted = FALSE AND mall_delivery_warehouse_id IS NOT NULL;

COMMENT ON COLUMN xsy_sales_order.mall_delivery_warehouse_id IS '商城订单提交时冻结的配送仓；历史订单为空';
