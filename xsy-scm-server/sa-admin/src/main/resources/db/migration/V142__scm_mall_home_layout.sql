CREATE TABLE xsy_mall_home_draft (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    schema_version INTEGER NOT NULL DEFAULT 1 CHECK (schema_version = 1),
    content JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(content) = 'array'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(64)
);
INSERT INTO xsy_mall_home_draft(id) VALUES (1);

CREATE TABLE xsy_mall_home_release (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_version INTEGER NOT NULL DEFAULT 1 CHECK (schema_version = 1),
    content JSONB NOT NULL CHECK (jsonb_typeof(content) = 'array'),
    publish_kind VARCHAR(16) NOT NULL CHECK (publish_kind IN ('PUBLISH', 'ROLLBACK')),
    source_release_id BIGINT,
    reason VARCHAR(500),
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_by VARCHAR(64) NOT NULL
);

CREATE TABLE xsy_mall_home_pointer (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    current_release_id BIGINT,
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(64)
);
INSERT INTO xsy_mall_home_pointer(id) VALUES (1);

CREATE FUNCTION xsy_reject_mall_home_release_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'mall home release is immutable' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER trg_mall_home_release_immutable
    BEFORE UPDATE OR DELETE OR TRUNCATE ON xsy_mall_home_release
    FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_mall_home_release_mutation();

