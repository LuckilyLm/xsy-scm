-- 客户商城服务端购物车（2026-10-10）。按登录账号隔离，跨端一致、换机不丢。
-- 商品可见性、客户价与库存不在此固化，读取时实时解析。
CREATE TABLE mall_cart_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT         NOT NULL,
    customer_id BIGINT         NOT NULL,
    sku_id      BIGINT         NOT NULL,
    quantity    NUMERIC(18, 4) NOT NULL CHECK (quantity > 0),
    version     INTEGER        NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted     BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(64)    NOT NULL,
    updated_by  VARCHAR(64)    NOT NULL
);

CREATE UNIQUE INDEX uk_mall_cart_item_account_sku
    ON mall_cart_item (account_id, sku_id) WHERE deleted = FALSE;
CREATE INDEX idx_mall_cart_item_customer
    ON mall_cart_item (customer_id) WHERE deleted = FALSE;

COMMENT ON TABLE mall_cart_item IS '客户商城服务端购物车行；按登录账号隔离，商品与价格不在此固化';
COMMENT ON COLUMN mall_cart_item.quantity IS '下单数量，四位小数定点；非标品为预估量，最终以实重结算';
