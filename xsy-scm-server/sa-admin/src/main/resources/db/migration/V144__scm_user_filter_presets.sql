CREATE TABLE xsy_user_filter_preset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(80) NOT NULL,
    view_key VARCHAR(32) NOT NULL
        CHECK (view_key IN ('PRODUCT', 'SALES_ORDER', 'PURCHASE_PRODUCT')),
    name VARCHAR(50) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 50),
    conditions JSONB NOT NULL
        CHECK (jsonb_typeof(conditions) = 'array'
            AND jsonb_array_length(conditions) BETWEEN 1 AND 8),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_filter_preset_name UNIQUE (owner_key, view_key, name)
);

CREATE INDEX idx_user_filter_preset_owner_view
    ON xsy_user_filter_preset(owner_key, view_key, id DESC);
