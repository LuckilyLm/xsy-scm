-- 抹零：把零头作为一项减免事实冲减应收，而不是「少收了一点」。
--
-- 现场口径（docs/decisions.md D-1028-09）：应收账款按客户对账时抹掉几分到几角。
-- 若不建模成事实，收款金额会永远与应收差一点，余额、账龄、对账单都会显示「欠 0.30 元」。
--
-- 实现：本表只记录「谁在什么时候因为什么免掉了多少」；真正的余额冲减仍是
-- xsy_finance_write_off 的一行（source_type='WAIVER'），因此未结额、账龄、对账单滚动余额
-- 全部沿用现有核销口径，不需要第二套余额公式。
--
-- 不落 status / reversed_at 等状态列：是否已反向完全由「该核销行有没有 REVERSE」推导
-- （xsy_finance_write_off.reverse_of_id + uk_finance_write_off_single_reverse），
-- 落库只会多一份会漂移的派生态（ScmFinanceSchemaPgIT 的状态列禁令同一口径）。

CREATE TABLE xsy_finance_waiver (
    id                     BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waiver_no              VARCHAR(64)   NOT NULL CHECK (btrim(waiver_no) <> ''),
    receivable_id          BIGINT        NOT NULL,
    customer_id            BIGINT        NOT NULL,
    settlement_customer_id BIGINT,
    amount                 NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    reason                 VARCHAR(500)  NOT NULL CHECK (btrim(reason) <> ''),
    version                INTEGER       NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted                BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by             VARCHAR(64),
    updated_by             VARCHAR(64),
    -- 抹零是财务事实，不允许软删；更正只能通过反向核销。
    CONSTRAINT ck_finance_waiver_append_only CHECK (deleted = FALSE)
);

CREATE UNIQUE INDEX uk_finance_waiver_no ON xsy_finance_waiver (waiver_no) WHERE deleted = FALSE;
CREATE INDEX idx_finance_waiver_receivable ON xsy_finance_waiver (receivable_id);

COMMENT ON TABLE xsy_finance_waiver IS '抹零事实；余额冲减由 source_type=WAIVER 的核销行承担，反向状态由该核销行是否被 REVERSE 推导';
COMMENT ON COLUMN xsy_finance_waiver.receivable_id IS '被抹零的应收单；只允许 NORMAL 应收';
COMMENT ON COLUMN xsy_finance_waiver.amount IS '抹零金额，必须大于 0；不允许用它代替收款';
COMMENT ON COLUMN xsy_finance_waiver.reason IS '抹零原因，必填；反向原因写在该反向核销行的 reason 上';
