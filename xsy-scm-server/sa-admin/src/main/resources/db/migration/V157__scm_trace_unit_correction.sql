-- 包装码更正：带审批的解绑，不做无痕解绑。
--
-- 规则：
-- 1. 绑定只追加，撤销也追加一条 unbind 事实，原绑定行不动；
-- 2. 一个包装码在同一时刻只能有一条有效绑定 —— 因此去掉 uk_trace_unit_binding_unit，
--    改由触发器保证「有效绑定唯一」（解绑后可以重新绑定，这才是更正的意义）；
-- 3. 申请与审批必须不是同一个人；一条绑定只能被批准撤销一次。

CREATE TABLE xsy_trace_unit_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    binding_id BIGINT NOT NULL,
    reason VARCHAR(200) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    requested_by VARCHAR(64) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    decided_by VARCHAR(64),
    decided_at TIMESTAMPTZ,
    decision_reason VARCHAR(200),
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    updated_at TIMESTAMPTZ,
    updated_by VARCHAR(64),
    CONSTRAINT ck_trace_unit_correction_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);
CREATE UNIQUE INDEX uk_trace_unit_correction_pending
    ON xsy_trace_unit_correction(unit_id) WHERE status = 'PENDING';
CREATE UNIQUE INDEX uk_trace_unit_correction_binding
    ON xsy_trace_unit_correction(binding_id) WHERE status = 'APPROVED';
CREATE INDEX idx_trace_unit_correction_status ON xsy_trace_unit_correction(status, id);
COMMENT ON TABLE xsy_trace_unit_correction IS '包装码更正申请：解绑必须经他人审批，申请与审批不得是同一人';

CREATE TABLE xsy_trace_unit_unbind (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    binding_id BIGINT NOT NULL,
    correction_id BIGINT NOT NULL,
    reason VARCHAR(200) NOT NULL,
    unbound_at TIMESTAMPTZ NOT NULL,
    unbound_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_trace_unit_unbind_binding UNIQUE (binding_id)
);
COMMENT ON TABLE xsy_trace_unit_unbind IS '包装码解绑事实：只追加；一条绑定只能被撤销一次';

CREATE FUNCTION xsy_reject_trace_unit_unbind_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'trace unit unbinds are append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER trg_trace_unit_unbind_append_only BEFORE UPDATE OR DELETE OR TRUNCATE
    ON xsy_trace_unit_unbind FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_trace_unit_unbind_mutation();

-- 事件类型放开到解绑
ALTER TABLE xsy_trace_event DROP CONSTRAINT ck_trace_event_type;
ALTER TABLE xsy_trace_event ADD CONSTRAINT ck_trace_event_type
    CHECK (event_type IN ('ISSUE', 'VOID', 'BIND', 'UNBIND'));

-- 有效绑定唯一：同一码同一时刻只能有一条未被撤销的绑定
ALTER TABLE xsy_trace_unit_binding DROP CONSTRAINT uk_trace_unit_binding_unit;

CREATE FUNCTION xsy_assert_unit_bindable() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    unit_status VARCHAR(16);
    active_bindings INT;
BEGIN
    SELECT status INTO unit_status FROM xsy_trace_unit WHERE id = NEW.unit_id;
    IF unit_status IS DISTINCT FROM 'ACTIVE' THEN
        RAISE EXCEPTION 'cannot bind a void trace unit' USING ERRCODE = '23514';
    END IF;
    SELECT count(*) INTO active_bindings
      FROM xsy_trace_unit_binding b
     WHERE b.unit_id = NEW.unit_id
       AND NOT EXISTS (SELECT 1 FROM xsy_trace_unit_unbind u WHERE u.binding_id = b.id);
    IF active_bindings > 0 THEN
        RAISE EXCEPTION 'trace unit already has an active binding' USING ERRCODE = '23505';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_trace_unit_binding_active ON xsy_trace_unit_binding;
CREATE TRIGGER trg_trace_unit_binding_active
    BEFORE INSERT ON xsy_trace_unit_binding
    FOR EACH ROW EXECUTE FUNCTION xsy_assert_unit_bindable();

