-- 订单标签仅供人工分类，不修改订单生命周期、价格、库存或履约事实。
-- 沿用订单的 seller 数据范围和 OrderPermission.QUERY/UPDATE 权限。
CREATE TABLE xsy_order_tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 32),
    color VARCHAR(12) NOT NULL DEFAULT 'BLUE'
        CHECK (color IN ('BLUE','GREEN','ORANGE','RED','PURPLE','GRAY')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_order_tag_name ON xsy_order_tag (lower(btrim(name)));

CREATE TABLE xsy_order_tag_link (
    order_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (order_id, tag_id)
);
CREATE INDEX idx_order_tag_link_tag_order ON xsy_order_tag_link (tag_id, order_id);

-- 业务关联沿用 xsy_v2 无外键约束，写入端按锁定订单检查可见范围，数据库仅记录分类。
