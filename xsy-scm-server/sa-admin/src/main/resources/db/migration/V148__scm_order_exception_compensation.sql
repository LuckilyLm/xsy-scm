-- Exchange links are created only after the approved return has been physically received.
-- The replacement remains an ordinary draft order with its own price, stock and funding lifecycle.
CREATE TABLE xsy_order_exchange_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL,
    original_order_id BIGINT NOT NULL,
    replacement_order_id BIGINT NOT NULL,
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_order_exchange_return ON xsy_order_exchange_link(return_id);
CREATE UNIQUE INDEX uk_order_exchange_replacement ON xsy_order_exchange_link(replacement_order_id);
CREATE INDEX idx_order_exchange_original ON xsy_order_exchange_link(original_order_id);

-- Customer-reported received quantity is an appended assertion. It never rewrites sales order,
-- delivery, inventory or finance facts; compensation uses their existing formal commands.
CREATE TABLE xsy_order_received_quantity_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    sale_unit_snapshot VARCHAR(32) NOT NULL,
    shipped_quantity NUMERIC(18,4) NOT NULL,
    previous_received_quantity NUMERIC(18,4) NOT NULL,
    received_quantity NUMERIC(18,4) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_received_correction_quantity CHECK (
        shipped_quantity > 0 AND previous_received_quantity BETWEEN 0 AND shipped_quantity
        AND received_quantity BETWEEN 0 AND shipped_quantity
        AND received_quantity <> previous_received_quantity),
    CONSTRAINT ck_received_correction_reason CHECK (btrim(reason) <> '')
);
CREATE INDEX idx_received_correction_order ON xsy_order_received_quantity_correction(order_id, id DESC);
CREATE INDEX idx_received_correction_item ON xsy_order_received_quantity_correction(order_item_id, id DESC);
