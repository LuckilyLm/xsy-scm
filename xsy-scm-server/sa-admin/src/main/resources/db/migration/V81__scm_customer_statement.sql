-- Frozen customer reconciliation is a read-side snapshot; Finance facts remain authoritative.
CREATE TABLE scm_customer_statement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_customer_id BIGINT NOT NULL,
    settlement_customer_name VARCHAR(150) NOT NULL,
    customer_id BIGINT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    partial_scope BOOLEAN NOT NULL,
    generated_by_employee_id BIGINT NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    opening_receivable NUMERIC(22,4) NOT NULL,
    receivable_increase NUMERIC(22,4) NOT NULL,
    receivable_red NUMERIC(22,4) NOT NULL,
    write_off_net NUMERIC(22,4) NOT NULL,
    closing_receivable NUMERIC(22,4) NOT NULL,
    opening_unallocated NUMERIC(22,4),
    receipt_net NUMERIC(22,4) NOT NULL,
    closing_unallocated NUMERIC(22,4),
    refund_net NUMERIC(22,4) NOT NULL,
    CONSTRAINT ck_customer_statement_period CHECK (start_date <= end_date)
);
CREATE INDEX idx_customer_statement_history ON scm_customer_statement
    (generated_by_employee_id, settlement_customer_id, generated_at DESC);

CREATE TABLE scm_customer_statement_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT NOT NULL REFERENCES scm_customer_statement(id),
    line_no INTEGER NOT NULL,
    fact_type VARCHAR(24) NOT NULL,
    fact_id BIGINT NOT NULL,
    event_at TIMESTAMPTZ NOT NULL,
    document_no VARCHAR(64) NOT NULL,
    related_no VARCHAR(64),
    customer_id BIGINT NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    receivable_delta NUMERIC(22,4) NOT NULL,
    receipt_delta NUMERIC(22,4) NOT NULL,
    write_off_delta NUMERIC(22,4) NOT NULL,
    refund_delta NUMERIC(22,4) NOT NULL,
    receivable_balance NUMERIC(22,4) NOT NULL,
    CONSTRAINT uk_customer_statement_line UNIQUE (statement_id, line_no),
    CONSTRAINT uk_customer_statement_fact UNIQUE (statement_id, fact_type, fact_id)
);
CREATE INDEX idx_customer_statement_item_statement ON scm_customer_statement_item(statement_id, line_no);
-- Record ALL contributing facts, including facts before the displayed period, for access revalidation.
CREATE TABLE scm_customer_statement_source (
    statement_id BIGINT NOT NULL REFERENCES scm_customer_statement(id),
    fact_type VARCHAR(24) NOT NULL,
    fact_id BIGINT NOT NULL,
    PRIMARY KEY (statement_id, fact_type, fact_id)
);

