CREATE TABLE xsy_mall_customer_account (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id                BIGINT       NOT NULL,
    login_phone                VARCHAR(32)  NOT NULL,
    password_hash              VARCHAR(255) NOT NULL,
    status                     VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    first_password_change      BOOLEAN      NOT NULL DEFAULT TRUE,
    login_failed_count         INTEGER      NOT NULL DEFAULT 0,
    locked_until               TIMESTAMPTZ,
    last_login_at              TIMESTAMPTZ,
    last_login_ip              VARCHAR(64),
    version                    INTEGER      NOT NULL DEFAULT 0,
    deleted                    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                 TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by                 VARCHAR(64),
    updated_by                 VARCHAR(64),
    CONSTRAINT ck_mall_customer_account_phone CHECK (login_phone = btrim(login_phone) AND login_phone <> ''),
    CONSTRAINT ck_mall_customer_account_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_mall_customer_account_failed CHECK (login_failed_count >= 0),
    CONSTRAINT ck_mall_customer_account_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_mall_customer_account_phone_active
    ON xsy_mall_customer_account (login_phone) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_mall_customer_account_customer_active
    ON xsy_mall_customer_account (customer_id) WHERE deleted = FALSE;
CREATE INDEX idx_mall_customer_account_status
    ON xsy_mall_customer_account (status) WHERE deleted = FALSE;

CREATE TABLE xsy_mall_wechat_binding (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT       NOT NULL,
    app_id             VARCHAR(64)  NOT NULL,
    open_id            VARCHAR(128) NOT NULL,
    union_id           VARCHAR(128),
    version            INTEGER      NOT NULL DEFAULT 0,
    deleted            BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by         VARCHAR(64),
    updated_by         VARCHAR(64),
    CONSTRAINT ck_mall_wechat_app_id CHECK (btrim(app_id) <> ''),
    CONSTRAINT ck_mall_wechat_open_id CHECK (btrim(open_id) <> ''),
    CONSTRAINT ck_mall_wechat_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_mall_wechat_app_open_active
    ON xsy_mall_wechat_binding (app_id, open_id) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_mall_wechat_union_active
    ON xsy_mall_wechat_binding (union_id) WHERE deleted = FALSE AND union_id IS NOT NULL;
CREATE UNIQUE INDEX uk_mall_wechat_account_app_active
    ON xsy_mall_wechat_binding (account_id, app_id) WHERE deleted = FALSE;

