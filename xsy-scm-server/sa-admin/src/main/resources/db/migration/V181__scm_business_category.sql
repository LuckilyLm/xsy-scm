-- 客户 / 供应商业务分类：只用于客户与供应商的可维护小树，不复用商品分类。
-- 商品分类有三级且末级绑定商品；本表按 scope 隔离，最多三级，不建数据库外键。

CREATE TABLE xsy_business_category (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope         VARCHAR(16)  NOT NULL,
    category_code VARCHAR(64)  NOT NULL,
    name          VARCHAR(64)  NOT NULL,
    parent_id     BIGINT,
    level         SMALLINT     NOT NULL DEFAULT 1,
    status        VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    sort_order    INTEGER      NOT NULL DEFAULT 0,
    version       INTEGER      NOT NULL DEFAULT 0,
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by    VARCHAR(64),
    updated_by    VARCHAR(64),
    CONSTRAINT ck_business_category_scope CHECK (scope IN ('CUSTOMER', 'SUPPLIER')),
    CONSTRAINT ck_business_category_level CHECK (level BETWEEN 1 AND 3),
    CONSTRAINT ck_business_category_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_business_category_version CHECK (version >= 0),
    CONSTRAINT ck_business_category_self_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE UNIQUE INDEX uk_business_category_code_active
    ON xsy_business_category (scope, category_code) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_business_category_name_active
    ON xsy_business_category (scope, name) WHERE deleted = FALSE;
CREATE INDEX idx_business_category_parent
    ON xsy_business_category (scope, parent_id, sort_order);

-- 历史客户 / 供应商保持未分类；分类由服务端按 scope 校验，不使用数据库外键。
ALTER TABLE xsy_customer ADD COLUMN business_category_id BIGINT;
CREATE INDEX idx_customer_business_category
    ON xsy_customer (business_category_id)
    WHERE deleted = FALSE AND business_category_id IS NOT NULL;

ALTER TABLE xsy_supplier ADD COLUMN business_category_id BIGINT;
CREATE INDEX idx_supplier_business_category
    ON xsy_supplier (business_category_id)
    WHERE deleted = FALSE AND business_category_id IS NOT NULL;

