CREATE SEQUENCE purchase_cost_adjustment_no_seq;
CREATE TABLE xsy_purchase_cost_adjustment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_no VARCHAR(64) NOT NULL UNIQUE,
    receipt_item_id BIGINT NOT NULL,
    receipt_id BIGINT NOT NULL,
    purchase_order_id BIGINT NOT NULL,
    purchase_order_item_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,
    supplier_name_snapshot VARCHAR(150) NOT NULL,
    sku_id BIGINT NOT NULL,
    product_name_snapshot VARCHAR(150) NOT NULL,
    unit_snapshot VARCHAR(32) NOT NULL,
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity > 0),
    previous_adjustment_id BIGINT,
    previous_price NUMERIC(18,4) NOT NULL CHECK (previous_price >= 0),
    new_price NUMERIC(18,4) NOT NULL CHECK (new_price >= 0),
    direction VARCHAR(16) NOT NULL CHECK (direction IN ('INCREASE', 'DECREASE')),
    amount NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    reason VARCHAR(500) NOT NULL CHECK (btrim(reason) <> ''),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64) NOT NULL,
    CHECK ((new_price > previous_price AND direction = 'INCREASE') OR (new_price < previous_price AND direction = 'DECREASE'))
);
CREATE INDEX idx_purchase_cost_adjustment_receipt ON xsy_purchase_cost_adjustment(receipt_item_id, id DESC);
CREATE INDEX idx_purchase_cost_adjustment_event ON xsy_purchase_cost_adjustment(occurred_at, warehouse_id);
CREATE UNIQUE INDEX uk_purchase_cost_adjustment_chain ON xsy_purchase_cost_adjustment(receipt_item_id, COALESCE(previous_adjustment_id, 0));

-- 一次调减可能分别冲减原收货应付和此前的调增应付，分配来源单独追加，避免共用一个来源编号。
CREATE TABLE xsy_finance_purchase_cost_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_id BIGINT NOT NULL,
    receipt_item_id BIGINT NOT NULL,
    original_payable_id BIGINT,
    amount NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64) NOT NULL
);
CREATE UNIQUE INDEX uk_finance_purchase_cost_entry ON xsy_finance_purchase_cost_entry(adjustment_id, COALESCE(original_payable_id, 0));
CREATE INDEX idx_finance_purchase_cost_entry_receipt ON xsy_finance_purchase_cost_entry(receipt_item_id);

CREATE FUNCTION scm_reject_cost_adjustment_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Purchase cost adjustment facts are append-only';
END;
$$;
CREATE TRIGGER trg_purchase_cost_adjustment_append_only BEFORE UPDATE OR DELETE ON xsy_purchase_cost_adjustment
    FOR EACH ROW EXECUTE FUNCTION scm_reject_cost_adjustment_mutation();
CREATE TRIGGER trg_finance_purchase_cost_entry_append_only BEFORE UPDATE OR DELETE ON xsy_finance_purchase_cost_entry
    FOR EACH ROW EXECUTE FUNCTION scm_reject_cost_adjustment_mutation();

