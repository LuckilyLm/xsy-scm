-- 追溯包装码（二期 L2 包装单元）。
--
-- 与批次的关系：一个包装码只属于一个批次（一码一批，不做混批），但一个批次可以有多个包装码。
-- 包装码是「贴在被包装实物上的身份」，与批次号严格区分：批次码不冒充逐包装码，
-- unit_code 由系统发号、不透明、不嵌日期、永不复用。

CREATE SEQUENCE trace_unit_seq;

CREATE TABLE xsy_trace_unit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_code VARCHAR(32) NOT NULL,
    lot_id BIGINT NOT NULL,
    package_type VARCHAR(16) NOT NULL DEFAULT 'BAG',
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_trace_unit_code UNIQUE (unit_code),
    CONSTRAINT ck_trace_unit_package_type CHECK (package_type IN ('BAG', 'BOX', 'CRATE')),
    CONSTRAINT ck_trace_unit_status CHECK (status IN ('ACTIVE', 'VOID'))
);
CREATE INDEX idx_trace_unit_lot ON xsy_trace_unit(lot_id, id);
COMMENT ON TABLE xsy_trace_unit IS '追溯包装单元：一码一批，code 不透明且永不复用，可作废但不可删除';
COMMENT ON COLUMN xsy_trace_unit.unit_code IS '系统发号的不透明码，不嵌日期与业务含义；作废后仍保留原码，不得复用';

CREATE TABLE xsy_trace_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT,
    lot_id BIGINT NOT NULL,
    event_type VARCHAR(24) NOT NULL,
    source_document_type VARCHAR(32),
    source_document_id BIGINT,
    source_document_item_id BIGINT,
    occurred_at TIMESTAMPTZ NOT NULL,
    operator VARCHAR(64) NOT NULL,
    remark VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT ck_trace_event_type CHECK (event_type IN ('ISSUE', 'VOID'))
);
CREATE INDEX idx_trace_event_unit ON xsy_trace_event(unit_id, id);
CREATE INDEX idx_trace_event_lot ON xsy_trace_event(lot_id, id);
COMMENT ON TABLE xsy_trace_event IS '包装码事件：只追加，作废也追加一条 VOID 而不是改写原行';

CREATE FUNCTION xsy_reject_trace_event_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'trace events are append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER trg_trace_event_append_only BEFORE UPDATE OR DELETE OR TRUNCATE
    ON xsy_trace_event FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_trace_event_mutation();

