CREATE TABLE xsy_customer_sku_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    alias VARCHAR(100) NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_sku_alias_version CHECK (version >= 0),
    CONSTRAINT ck_customer_sku_alias_nonblank CHECK (length(btrim(alias)) > 0)
);

CREATE UNIQUE INDEX uk_customer_sku_alias_active
    ON xsy_customer_sku_alias (customer_id, sku_id) WHERE deleted = FALSE;
CREATE INDEX idx_customer_sku_alias_customer ON xsy_customer_sku_alias (customer_id) WHERE deleted = FALSE;
