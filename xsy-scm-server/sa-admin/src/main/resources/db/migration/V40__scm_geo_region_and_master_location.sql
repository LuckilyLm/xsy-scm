-- ---------------------------------------------------------------------------
-- Step 4: 存量地址保守解析到市
-- ---------------------------------------------------------------------------
-- 规则刻意保守，宁缺勿错：
--   * 只按区划**完整名称**（'杭州市' 而非 '杭州'）做 strpos 匹配，街道里出现「长沙路」不会命中；
--   * 命中多个市时取**出现位置最早**的那个（地址一般「省→市→区」，最早者最可信）；
--   * 市名在全国不唯一时（当前只有重庆市），必须同时命中其省名才允许匹配，并列取编码较小者；
--   * 只解析到市；解析不出就留 NULL，由 M2 的地图选点或人工补录解决，不猜。
DO $$
DECLARE
    t             TEXT;
    city_hits     INTEGER;
    province_hits INTEGER;
BEGIN
    FOREACH t IN ARRAY ARRAY['warehouse', 'customer', 'supplier'] LOOP
        EXECUTE format('
            WITH candidates AS (
                SELECT src.id AS row_id,
                       city.region_code,
                       city.parent_code,
                       city.region_name AS city_name,
                       province.region_name AS province_name,
                       ROW_NUMBER() OVER (
                           PARTITION BY src.id
                           ORDER BY strpos(src.address, city.region_name), city.region_code
                       ) AS rn
                FROM %1$I src
                JOIN scm_region city
                  ON city.deleted = FALSE AND city.region_level = 2
                 AND strpos(src.address, city.region_name) > 0
                JOIN scm_region province
                  ON province.deleted = FALSE AND province.region_code = city.parent_code
                WHERE src.deleted = FALSE
                  AND src.city_code IS NULL
                  AND coalesce(src.address, '''') <> ''''
                  AND (
                        (SELECT COUNT(*) FROM scm_region same
                          WHERE same.deleted = FALSE AND same.region_level = 2
                            AND same.region_name = city.region_name) = 1
                        OR strpos(src.address, province.region_name) > 0
                      )
            )
            UPDATE %1$I src
               SET city_code     = c.region_code,
                   city_name     = c.city_name,
                   province_code = c.parent_code,
                   province_name = c.province_name,
                   updated_at    = CURRENT_TIMESTAMP
              FROM candidates c
             WHERE c.row_id = src.id AND c.rn = 1', t);

        GET DIAGNOSTICS city_hits = ROW_COUNT;

        -- 只有省名可辨时，至少把省补齐，让省级统计不丢行。
        EXECUTE format('
            WITH candidates AS (
                SELECT src.id AS row_id,
                       prov.region_code,
                       prov.region_name,
                       ROW_NUMBER() OVER (
                           PARTITION BY src.id
                           ORDER BY strpos(src.address, prov.region_name), prov.region_code
                       ) AS rn
                FROM %1$I src
                JOIN scm_region prov
                  ON prov.deleted = FALSE AND prov.region_level = 1
                 AND strpos(src.address, prov.region_name) > 0
                WHERE src.deleted = FALSE
                  AND src.province_code IS NULL
                  AND coalesce(src.address, '''') <> ''''
            )
            UPDATE %1$I src
               SET province_code = c.region_code,
                   province_name = c.region_name,
                   updated_at    = CURRENT_TIMESTAMP
              FROM candidates c
             WHERE c.row_id = src.id AND c.rn = 1', t);

        GET DIAGNOSTICS province_hits = ROW_COUNT;
        RAISE NOTICE 'V40 地址解析 %：市级 % 行，仅省级 % 行', t, city_hits, province_hits;
    END LOOP;
END $$;
