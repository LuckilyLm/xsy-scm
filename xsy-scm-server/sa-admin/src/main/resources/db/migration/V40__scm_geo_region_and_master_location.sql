-- V40: 地图模块 M0 —— 行政区划字典（省 / 市两级）与三张主档的地理归属，2026-09-21。
--
-- 方案见 docs/requirements/2026-09-21-地图模块分期实施方案.md §3。
-- 为什么只有省市两级：区县由前端 area-cascader 人工选择后按「编码 + 名称快照」直接落库，
-- 服务端不需要区县字典。scm_region 存在的理由只有两个，且都需要服务端持有数据：
--   ① 存量自由文本地址要保守解析到市（人工不可能覆盖几百家客户）；
--   ② 大屏按市聚合气泡时必须能拿到市的质心坐标。
-- 坐标系约定：center_lng / center_lat 以及后续 M2 补录的业务坐标一律按 GCJ-02 理解。
-- GCJ-02（高德 / 腾讯 / DataV）与 WGS-84（天地图 / OSM）混用会带来百米级系统偏移且事后
-- 无法追溯，因此每张表都带 geom_crs 标记，而不是靠「大家都知道是高德」的口头约定。
-- 种子来源：区划编码与名称取自仓库内 xsy-scm-web/src/components/framework/area-cascader/
-- province-city-district.ts（GB/T 2260 六位码，与前端选择器逐字一致，避免两套编码对不上），
-- 质心取自阿里 DataV.GeoAtlas areas_v3（拉取日期 2026-09-21，港澳台等无市级要素的省回落省质心）。
-- 沿用项目约定：无外键、逻辑删除、乐观锁 version、TIMESTAMPTZ、关系列显式建索引。

-- ---------------------------------------------------------------------------
-- Step 1: 行政区划字典
-- ---------------------------------------------------------------------------
CREATE TABLE scm_region (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_code  INTEGER      NOT NULL,
    parent_code  INTEGER,
    region_name  VARCHAR(64)  NOT NULL,
    region_level SMALLINT     NOT NULL,
    center_lng   NUMERIC(11,8),
    center_lat   NUMERIC(10,8),
    version      INTEGER      NOT NULL DEFAULT 0,
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by   VARCHAR(64),
    updated_by   VARCHAR(64),
    CONSTRAINT ck_scm_region_level  CHECK (region_level IN (1, 2)),
    CONSTRAINT ck_scm_region_parent CHECK ((parent_code IS NULL) = (region_level = 1)),
    CONSTRAINT ck_scm_region_lng    CHECK (center_lng IS NULL OR (center_lng >= -180 AND center_lng <= 180)),
    CONSTRAINT ck_scm_region_lat    CHECK (center_lat IS NULL OR (center_lat >= -90 AND center_lat <= 90)),
    CONSTRAINT ck_scm_region_version CHECK (version >= 0)
);
CREATE UNIQUE INDEX uk_scm_region_code_active ON scm_region (region_code) WHERE deleted = FALSE;
CREATE INDEX idx_scm_region_parent_active ON scm_region (parent_code) WHERE deleted = FALSE;
-- 存量地址解析按名称查市，是迁移期的一次性热点路径，留一条名称索引避免全表扫。
CREATE INDEX idx_scm_region_name_active ON scm_region (region_name) WHERE deleted = FALSE;

COMMENT ON TABLE scm_region IS '行政区划字典（省 / 市两级），供地址保守解析与大屏按市聚合取质心';
COMMENT ON COLUMN scm_region.region_code  IS '国标六位行政区划码，与前端省市区选择器同源同值';
COMMENT ON COLUMN scm_region.parent_code  IS '上级区划码：市级指向省级，省级为 NULL';
COMMENT ON COLUMN scm_region.region_level IS '层级：1 省 / 2 市；区县级不入库，由业务表单按名称快照维护';
COMMENT ON COLUMN scm_region.center_lng   IS '区划质心经度，GCJ-02；仅用于地图定位，不是任何单位的实际地址坐标';
COMMENT ON COLUMN scm_region.center_lat   IS '区划质心纬度，GCJ-02';
COMMENT ON COLUMN scm_region.region_name  IS '区划名称快照；业务表同时存编码与名称，名称不参与关联';

