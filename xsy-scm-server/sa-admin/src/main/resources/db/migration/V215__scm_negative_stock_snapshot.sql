CREATE SEQUENCE report_negative_stock_snapshot_no_seq;
CREATE TABLE xsy_report_negative_stock_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_no VARCHAR(64) NOT NULL UNIQUE,
    warehouse_id BIGINT NOT NULL,
    warehouse_name VARCHAR(100) NOT NULL,
    snapshot_month DATE NOT NULL CHECK (EXTRACT(DAY FROM snapshot_month) = 1),
    captured_at TIMESTAMPTZ NOT NULL,
    row_count BIGINT NOT NULL CHECK (row_count >= 0),
    zero_cost_row_count BIGINT NOT NULL CHECK (zero_cost_row_count >= 0),
    estimated_amount NUMERIC(38,4) NOT NULL,
    row_data JSONB NOT NULL CHECK (jsonb_typeof(row_data) = 'array'),
    remark VARCHAR(500),
    created_by VARCHAR(64) NOT NULL,
    CHECK (jsonb_array_length(row_data) = row_count)
);
CREATE INDEX idx_report_negative_stock_snapshot_month ON xsy_report_negative_stock_snapshot(snapshot_month, warehouse_id, id DESC);
CREATE FUNCTION scm_reject_negative_snapshot_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Negative stock snapshots are append-only';
END;
$$;
CREATE TRIGGER trg_negative_stock_snapshot_append_only BEFORE UPDATE OR DELETE ON xsy_report_negative_stock_snapshot
    FOR EACH ROW EXECUTE FUNCTION scm_reject_negative_snapshot_mutation();
