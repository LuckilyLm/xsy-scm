CREATE SEQUENCE finance_customer_expense_no_seq;

CREATE TABLE xsy_finance_customer_expense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_no VARCHAR(64) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    customer_name_snapshot VARCHAR(150) NOT NULL,
    expense_month DATE NOT NULL CHECK (EXTRACT(DAY FROM expense_month) = 1),
    tax_amount NUMERIC(18,4) NOT NULL CHECK (tax_amount >= 0),
    service_amount NUMERIC(18,4) NOT NULL CHECK (service_amount >= 0),
    freight_amount NUMERIC(18,4) NOT NULL CHECK (freight_amount >= 0),
    commission_amount NUMERIC(18,4) NOT NULL CHECK (commission_amount >= 0),
    reason VARCHAR(500) NOT NULL CHECK (btrim(reason) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64) NOT NULL,
    CHECK (tax_amount + service_amount + freight_amount + commission_amount > 0)
);
CREATE INDEX idx_finance_customer_expense_month ON xsy_finance_customer_expense(expense_month, customer_id);
CREATE TABLE xsy_finance_customer_expense_void (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id BIGINT NOT NULL UNIQUE,
    reason VARCHAR(500) NOT NULL CHECK (btrim(reason) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64) NOT NULL
);
COMMENT ON TABLE xsy_finance_customer_expense IS '客户月费用实际金额；追加记录，不生成应收应付或资金事实';
COMMENT ON TABLE xsy_finance_customer_expense_void IS '客户月费用作废事实；原记录保留';

CREATE FUNCTION scm_reject_customer_expense_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Customer expense facts are append-only';
END;
$$;
CREATE TRIGGER trg_customer_expense_append_only BEFORE UPDATE OR DELETE ON xsy_finance_customer_expense
    FOR EACH ROW EXECUTE FUNCTION scm_reject_customer_expense_mutation();
CREATE TRIGGER trg_customer_expense_void_append_only BEFORE UPDATE OR DELETE ON xsy_finance_customer_expense_void
    FOR EACH ROW EXECUTE FUNCTION scm_reject_customer_expense_mutation();

