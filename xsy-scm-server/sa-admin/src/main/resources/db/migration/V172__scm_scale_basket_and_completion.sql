-- SDP-05 电子秤多筐：逐筐原始事实 + 商品集合完成。
--
-- 边界：
--   * 每筐仍是一条 xsy_sorting_scale_event，沿用 V89 的 event_key 幂等与 captured_at 时钟校验；
--     这里只补「筐号、净重与换算依据、设备会话」这些多筐才需要的列，不改变原有单事件语义。
--   * 集合完成单独成表：一次人工确认对应一个 operation_id，是幂等键，也是「哪些筐被一起确认」的证据。
--   * 正式分拣数量仍只由 SortingTaskService.enter 写入。本迁移不新增任何直接改分拣量的路径，
--     也不放宽 raw_reading >= 0：负值读数属于设备侧无效采集，服务端拒绝，不用约束兜底掩盖。
--   * 不新增数据库外键（V109 已确立），跨对象关联由领域服务在同一事务内校验。

ALTER TABLE xsy_sorting_scale_event
    -- 筐号在单个明细内从 1 递增；同一明细同一筐号只能出现一次。
    ADD COLUMN basket_no          INTEGER,
    -- 秤端一次人工操作的幂等号，重试复用；与 event_key 分工不同：后者标识一筐事实，前者标识一次操作。
    ADD COLUMN operation_id       VARCHAR(160),
    -- 员工授权会话；把「这台秤上的这次操作」与具体员工绑定，事后可追溯。
    ADD COLUMN device_session_id  BIGINT,
    ADD COLUMN job_version        VARCHAR(40),
    ADD COLUMN task_item_version  INTEGER,
    -- 业务计量单位与换算后净重。设备原始值仍在 raw_reading / unit，两者都保留才能复算。
    ADD COLUMN business_unit      VARCHAR(32),
    ADD COLUMN net_weight         NUMERIC(18, 4),
    ADD COLUMN weight_kind        VARCHAR(8),
    ADD COLUMN conversion_rule    VARCHAR(32),
    ADD COLUMN tare_weight        NUMERIC(18, 4),
    -- 稳定结论的来源。设备没有可信硬件稳定标记时不得伪称 DEVICE。
    ADD COLUMN stability_source   VARCHAR(32),
    ADD COLUMN protocol_type      VARCHAR(40),
    ADD COLUMN agent_version      VARCHAR(40),
    -- 集合完成记录；为空表示这筐还未被任何完成操作覆盖。
    ADD COLUMN completion_id      BIGINT;

ALTER TABLE xsy_sorting_scale_event
    ADD CONSTRAINT ck_sorting_scale_event_basket_no
        CHECK (basket_no IS NULL OR basket_no > 0),
    ADD CONSTRAINT ck_sorting_scale_event_weight_kind
        CHECK (weight_kind IS NULL OR weight_kind IN ('NET', 'GROSS')),
    -- 净重与业务单位必须成对出现：只有净重没有单位，或只有单位没有净重，都无法参与求和。
    ADD CONSTRAINT ck_sorting_scale_event_net_weight
        CHECK ((net_weight IS NULL AND business_unit IS NULL)
            OR (net_weight IS NOT NULL AND business_unit IS NOT NULL AND net_weight >= 0));

-- 一次人工操作只产生一条事实；重试命中同一 operation_id 时返回原记录而不是再写一筐。
CREATE UNIQUE INDEX uk_sorting_scale_event_operation
    ON xsy_sorting_scale_event (operation_id) WHERE operation_id IS NOT NULL;

-- 同一明细的筐号不可重复：设备重复提交换筐动作必须被拒绝，不能靠界面禁用按钮。
CREATE UNIQUE INDEX uk_sorting_scale_event_basket
    ON xsy_sorting_scale_event (task_item_id, basket_no) WHERE basket_no IS NOT NULL;

CREATE INDEX idx_sorting_scale_event_item_basket
    ON xsy_sorting_scale_event (task_item_id, basket_no) WHERE basket_no IS NOT NULL;

COMMENT ON COLUMN xsy_sorting_scale_event.basket_no IS '明细内递增的筐号，从 1 开始；同一明细同一筐号唯一';
COMMENT ON COLUMN xsy_sorting_scale_event.operation_id IS '秤端一次人工操作的幂等号；重试复用，不重新生成';
COMMENT ON COLUMN xsy_sorting_scale_event.device_session_id IS '关联 xsy_scale_device_session.id；标识这台秤上的哪位员工';
COMMENT ON COLUMN xsy_sorting_scale_event.job_version IS '采集时冻结的作业版本；任务改派后旧筐不能用于新的完成';
COMMENT ON COLUMN xsy_sorting_scale_event.task_item_version IS '采集时冻结的明细版本；用于发现任务重开导致的上下文过时';
COMMENT ON COLUMN xsy_sorting_scale_event.business_unit IS '换算后的业务计量单位；必须与明细销售单位一致才可完成';
COMMENT ON COLUMN xsy_sorting_scale_event.net_weight IS '换算后的净重；原始值与原始单位仍保留在 raw_reading / unit';
COMMENT ON COLUMN xsy_sorting_scale_event.weight_kind IS 'NET 净重 / GROSS 毛重；毛重不得在未去皮时直接入库';
COMMENT ON COLUMN xsy_sorting_scale_event.conversion_rule IS '原始单位到业务单位的换算依据；IDENTITY 表示同单位';
COMMENT ON COLUMN xsy_sorting_scale_event.tare_weight IS '设备提供的皮重；未提供时保持为空，不补零';
COMMENT ON COLUMN xsy_sorting_scale_event.stability_source IS '稳定结论来源：DEVICE 硬件标记 / MANUAL_CONFIRMED 人工确认';
COMMENT ON COLUMN xsy_sorting_scale_event.completion_id IS '关联 xsy_scale_item_completion.id；为空表示尚未被集合完成覆盖';

CREATE TABLE xsy_scale_item_completion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id VARCHAR(160) NOT NULL,
    task_id BIGINT NOT NULL,
    task_item_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL,
    device_session_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    -- 参与本次完成的筐数与总量。总量由服务端按筐重算，不采信设备提交的数字。
    basket_count INTEGER NOT NULL,
    total_quantity NUMERIC(18, 4) NOT NULL,
    business_unit VARCHAR(32) NOT NULL,
    -- 设备提交的集合摘要；服务端按同一算法复算后才允许完成。
    manifest_hash VARCHAR(64) NOT NULL,
    result VARCHAR(16) NOT NULL,
    reason VARCHAR(500),
    -- 确认前的已分拣量，便于事后核对差额；不是第二套数量事实。
    quantity_before NUMERIC(18, 4),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_scale_item_completion_operation UNIQUE (operation_id),
    CONSTRAINT ck_scale_item_completion_count CHECK (basket_count > 0),
    CONSTRAINT ck_scale_item_completion_total CHECK (total_quantity >= 0),
    CONSTRAINT ck_scale_item_completion_result CHECK (result IN ('NORMAL', 'SHORT', 'OUT_OF_STOCK', 'OVER'))
);

CREATE INDEX idx_scale_item_completion_item ON xsy_scale_item_completion (task_item_id, id DESC);

COMMENT ON TABLE xsy_scale_item_completion IS '电子秤商品集合完成事实：一次人工确认对应的筐集合、总量与结果，幂等键为 operation_id';
COMMENT ON COLUMN xsy_scale_item_completion.operation_id IS '秤端完成操作的幂等号；重复提交返回原完成结果';
COMMENT ON COLUMN xsy_scale_item_completion.basket_count IS '参与本次完成的筐数；由服务端按实际筐记录统计';
COMMENT ON COLUMN xsy_scale_item_completion.total_quantity IS '服务端按筐重算的累计净重，不采信设备提交的合计';
COMMENT ON COLUMN xsy_scale_item_completion.manifest_hash IS '设备提交的有序事件键集合摘要；服务端复算一致才允许完成';
COMMENT ON COLUMN xsy_scale_item_completion.result IS 'NORMAL / SHORT / OUT_OF_STOCK / OVER，与分拣结果枚举一致';
COMMENT ON COLUMN xsy_scale_item_completion.quantity_before IS '确认前该明细的已分拣量，用于核对差额与原因';
