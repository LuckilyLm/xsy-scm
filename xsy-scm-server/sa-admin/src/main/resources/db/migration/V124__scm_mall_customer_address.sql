-- 客户商城收货地址（2026-10-10）。归属客户，地理列形态与 V40 给 customer/warehouse/supplier 的一致。
CREATE TABLE xsy_mall_customer_address (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT       NOT NULL,
    receiver_name  VARCHAR(64)  NOT NULL,
    receiver_phone VARCHAR(32)  NOT NULL,
    province_code  INTEGER,
    province_name  VARCHAR(32),
    city_code      INTEGER,
    city_name      VARCHAR(64),
    district_code  INTEGER,
    district_name  VARCHAR(64),
    detail_address VARCHAR(255) NOT NULL,
    longitude      NUMERIC(11, 8),
    latitude       NUMERIC(10, 8),
    geom_crs       VARCHAR(8),
    is_default     BOOLEAN      NOT NULL DEFAULT FALSE,
    version        INTEGER      NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(64)  NOT NULL,
    updated_by     VARCHAR(64)  NOT NULL,
    CONSTRAINT ck_mall_customer_address_receiver CHECK (btrim(receiver_name) <> '' AND btrim(receiver_phone) <> ''),
    CONSTRAINT ck_mall_customer_address_detail CHECK (btrim(detail_address) <> ''),
    CONSTRAINT ck_mall_customer_address_coordinate_pair CHECK ((longitude IS NULL) = (latitude IS NULL)),
    CONSTRAINT ck_mall_customer_address_crs CHECK (geom_crs IS NULL OR geom_crs = 'GCJ02')
);

-- 一个客户至多一个默认收货地址
CREATE UNIQUE INDEX uk_mall_customer_address_default
    ON xsy_mall_customer_address (customer_id) WHERE deleted = FALSE AND is_default = TRUE;
CREATE INDEX idx_mall_customer_address_customer
    ON xsy_mall_customer_address (customer_id) WHERE deleted = FALSE;

COMMENT ON TABLE xsy_mall_customer_address IS '客户商城收货地址；归属客户，多个采购账号共享';
COMMENT ON COLUMN xsy_mall_customer_address.geom_crs IS '坐标系统标记，与 V40 主数据地理列一致';
