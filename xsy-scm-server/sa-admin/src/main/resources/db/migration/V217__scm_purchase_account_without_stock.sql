CREATE SEQUENCE purchase_account_no_seq;
CREATE TABLE xsy_purchase_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no VARCHAR(64) NOT NULL UNIQUE,
    purchase_order_id BIGINT NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL,
    supplier_name_snapshot VARCHAR(150) NOT NULL,
    warehouse_id BIGINT NOT NULL,
    remark VARCHAR(500),
    confirmed_at TIMESTAMPTZ NOT NULL,
    confirmed_by VARCHAR(100) NOT NULL
);
CREATE TABLE xsy_purchase_account_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    purchase_order_item_id BIGINT NOT NULL UNIQUE,
    sku_id BIGINT NOT NULL,
    product_name_snapshot VARCHAR(150) NOT NULL,
    sku_name_snapshot VARCHAR(150) NOT NULL,
    unit_snapshot VARCHAR(32) NOT NULL,
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity >= 0),
    unit_price NUMERIC(18,4) NOT NULL CHECK (unit_price >= 0),
    amount NUMERIC(18,4) NOT NULL CHECK (amount = round(quantity * unit_price, 4))
);
CREATE INDEX idx_purchase_account_item_account ON xsy_purchase_account_item(account_id);
CREATE TRIGGER trg_purchase_account_append_only BEFORE UPDATE OR DELETE ON xsy_purchase_account
    FOR EACH ROW EXECUTE FUNCTION scm_reject_cost_adjustment_mutation();
CREATE TRIGGER trg_purchase_account_item_append_only BEFORE UPDATE OR DELETE ON xsy_purchase_account_item
    FOR EACH ROW EXECUTE FUNCTION scm_reject_cost_adjustment_mutation();
COMMENT ON TABLE xsy_purchase_account IS '采购数量和价格确认事实；不产生收货或库存流水';
COMMENT ON TABLE xsy_purchase_account_item IS '确认时的实际采购数量和价格快照；零数量表示本次未采购';

