CREATE TABLE xsy_purchase_inquiry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    purchaser_id BIGINT,
    sku_id BIGINT NOT NULL,
    sku_code_snapshot VARCHAR(64) NOT NULL,
    product_name_snapshot VARCHAR(150) NOT NULL,
    demand_unit VARCHAR(32) NOT NULL,
    required_quantity NUMERIC(18,4) NOT NULL CHECK (required_quantity > 0),
    deadline_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'ACCEPTED')),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    accepted_quote_id BIGINT,
    accepted_at TIMESTAMPTZ,
    accepted_by VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_purchase_inquiry_source UNIQUE (batch_id, sku_id, demand_unit),
    CONSTRAINT ck_purchase_inquiry_accept CHECK
       ((status = 'OPEN' AND accepted_quote_id IS NULL AND accepted_at IS NULL AND accepted_by IS NULL)
        OR (status = 'ACCEPTED' AND accepted_quote_id IS NOT NULL AND accepted_at IS NOT NULL AND accepted_by IS NOT NULL))
);
CREATE INDEX idx_purchase_inquiry_batch ON xsy_purchase_inquiry(batch_id, id);

CREATE TABLE xsy_purchase_inquiry_quote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,
    supplier_name_snapshot VARCHAR(150) NOT NULL,
    revision INTEGER NOT NULL CHECK (revision > 0),
    purchase_unit VARCHAR(32) NOT NULL,
    unit_price NUMERIC(18,4) NOT NULL CHECK (unit_price >= 0),
    valid_until TIMESTAMPTZ NOT NULL,
    remark VARCHAR(500),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_purchase_inquiry_quote_revision UNIQUE (inquiry_id, supplier_id, revision)
);
CREATE INDEX idx_purchase_inquiry_quote_order ON xsy_purchase_inquiry_quote(inquiry_id, supplier_id, revision DESC);

-- No business foreign keys in xsy_v2. Keep source fields immutable and enforce the accepted quote's
-- ownership in the same database transaction (in addition to service-level locking).
CREATE FUNCTION xsy_guard_purchase_inquiry_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = 'ACCEPTED' THEN
        RAISE EXCEPTION 'accepted purchase inquiry cannot be changed' USING ERRCODE='23514';
    END IF;
    IF (NEW.batch_id, NEW.warehouse_id, NEW.purchaser_id, NEW.sku_id, NEW.sku_code_snapshot,
        NEW.product_name_snapshot, NEW.demand_unit, NEW.required_quantity, NEW.deadline_at,
        NEW.created_by) IS DISTINCT FROM
       (OLD.batch_id, OLD.warehouse_id, OLD.purchaser_id, OLD.sku_id, OLD.sku_code_snapshot,
        OLD.product_name_snapshot, OLD.demand_unit, OLD.required_quantity, OLD.deadline_at,
        OLD.created_by) THEN
        RAISE EXCEPTION 'purchase inquiry source is immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.status = 'ACCEPTED' AND NOT EXISTS (
        SELECT 1 FROM xsy_purchase_inquiry_quote q
        WHERE q.id = NEW.accepted_quote_id AND q.inquiry_id = NEW.id
    ) THEN
        RAISE EXCEPTION 'selected quote does not belong to inquiry' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_purchase_inquiry_guard BEFORE UPDATE ON xsy_purchase_inquiry
    FOR EACH ROW EXECUTE FUNCTION xsy_guard_purchase_inquiry_update();
CREATE FUNCTION xsy_reject_purchase_quote_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'purchase inquiry quote revisions are immutable' USING ERRCODE='23514';
END $$;
CREATE TRIGGER trg_purchase_inquiry_quote_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
    ON xsy_purchase_inquiry_quote FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_purchase_quote_mutation();

