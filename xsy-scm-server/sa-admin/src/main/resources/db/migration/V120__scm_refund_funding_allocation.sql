-- ADM-12 d：一张业务退款按原订单成功资金来源冻结分摊计划。
CREATE TABLE xsy_refund_funding_allocation (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_refund_id       BIGINT NOT NULL,
    order_id              BIGINT NOT NULL,
    customer_id           BIGINT NOT NULL,
    settlement_customer_id BIGINT NOT NULL,
    source_method         VARCHAR(16) NOT NULL CHECK (source_method IN ('BALANCE', 'ONLINE')),
    source_id             BIGINT NOT NULL,
    source_principal      NUMERIC(18, 4) NOT NULL CHECK (source_principal > 0),
    allocated_amount      NUMERIC(18, 4) NOT NULL CHECK (allocated_amount > 0),
    status                VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'FAILED')),
    result_source_id      BIGINT,
    failure_code          VARCHAR(64),
    failure_message       VARCHAR(500),
    source_succeeded_at   TIMESTAMPTZ NOT NULL,
    sort_order            INTEGER NOT NULL CHECK (sort_order >= 0),
    version               INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted               BOOLEAN NOT NULL DEFAULT FALSE CHECK (deleted = FALSE),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by            VARCHAR(64) NOT NULL,
    updated_by            VARCHAR(64) NOT NULL,
    CONSTRAINT ck_refund_funding_allocation_result CHECK (
        (status = 'SUCCEEDED' AND result_source_id IS NOT NULL AND failure_code IS NULL AND failure_message IS NULL)
        OR (status = 'FAILED' AND result_source_id IS NULL)
        OR (status IN ('PENDING', 'PROCESSING') AND result_source_id IS NULL
            AND failure_code IS NULL AND failure_message IS NULL))
);

CREATE UNIQUE INDEX uk_refund_funding_allocation_source
    ON xsy_refund_funding_allocation(order_refund_id, source_method, source_id) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_refund_funding_allocation_order
    ON xsy_refund_funding_allocation(order_refund_id, sort_order) WHERE deleted = FALSE;
CREATE INDEX idx_refund_funding_allocation_order_id
    ON xsy_refund_funding_allocation(order_id, order_refund_id) WHERE deleted = FALSE;

COMMENT ON TABLE xsy_refund_funding_allocation IS '订单售后退款按原成功资金来源冻结的不可变分摊事实';
COMMENT ON COLUMN xsy_refund_funding_allocation.source_id IS 'BALANCE 指 xsy_customer_balance_movement.id；ONLINE 指 xsy_payment_transaction.id';
COMMENT ON COLUMN xsy_refund_funding_allocation.result_source_id IS 'BALANCE 指返还流水 id；ONLINE 指 xsy_payment_refund.id';
COMMENT ON COLUMN xsy_refund_funding_allocation.source_principal IS '生成计划时该来源的剩余可退本金快照';
COMMENT ON COLUMN xsy_refund_funding_allocation.allocated_amount IS '按剩余本金比例分摊并归集四位小数尾差后的冻结金额';

ALTER TABLE xsy_payment_refund DROP CONSTRAINT ck_payment_refund_source_type;
ALTER TABLE xsy_payment_refund ADD CONSTRAINT ck_payment_refund_source_type CHECK (
    source_type IS NULL OR source_type IN ('ORDER_REFUND', 'REFUND_FUNDING_ALLOCATION'));
DROP INDEX uk_payment_refund_source;
CREATE UNIQUE INDEX uk_payment_refund_source ON xsy_payment_refund(source_type, source_id)
    WHERE deleted = FALSE AND source_type IS NOT NULL;
COMMENT ON COLUMN xsy_payment_refund.source_type IS 'ORDER_REFUND 旧单来源；REFUND_FUNDING_ALLOCATION 为资金分摊行';

ALTER TABLE xsy_customer_balance_movement DROP CONSTRAINT ck_customer_balance_movement_source_type;
ALTER TABLE xsy_customer_balance_movement ADD CONSTRAINT ck_customer_balance_movement_source_type CHECK (
    source_type IS NULL OR source_type IN (
        'PAYMENT_TRANSACTION', 'PAYMENT_INTENT', 'ORDER_REFUND', 'REFUND_FUNDING_ALLOCATION'));
ALTER TABLE xsy_customer_balance_movement DROP CONSTRAINT ck_customer_balance_movement_business_source;
ALTER TABLE xsy_customer_balance_movement ADD CONSTRAINT ck_customer_balance_movement_business_source CHECK (
    (type = 'RECHARGE' AND direction = 'CREDIT' AND source_type = 'PAYMENT_TRANSACTION' AND source_id IS NOT NULL)
    OR (type = 'CONSUME' AND direction = 'DEBIT' AND source_type = 'PAYMENT_INTENT' AND source_id IS NOT NULL)
    OR (type = 'REFUND' AND direction = 'CREDIT'
        AND source_type IN ('ORDER_REFUND', 'REFUND_FUNDING_ALLOCATION') AND source_id IS NOT NULL)
    OR (type = 'CORRECTION' AND source_type IS NULL AND source_id IS NULL
        AND btrim(COALESCE(reason, '')) <> ''));
COMMENT ON COLUMN xsy_customer_balance_movement.source_type IS '充值交易、订单余额消费、旧售后退款或退款资金分摊来源';

ALTER TABLE xsy_finance_payment DROP CONSTRAINT ck_finance_payment_method;
ALTER TABLE xsy_finance_payment ADD CONSTRAINT ck_finance_payment_method CHECK (
    (counterparty_type = 'SUPPLIER' AND method IN ('CASH', 'BANK_TRANSFER', 'OTHER'))
    OR (counterparty_type = 'CUSTOMER'
        AND method IN ('CASH', 'BANK_TRANSFER', 'ONLINE_PAYMENT', 'ORIGINAL_FUNDING', 'OTHER')));
COMMENT ON CONSTRAINT ck_finance_payment_method ON xsy_finance_payment IS
    '供应商付款保持三种人工方式；客户退款可按原资金来源聚合登记';
