ALTER TABLE xsy_payment_refund
    ADD COLUMN recovery_attempts INTEGER NOT NULL DEFAULT 0 CHECK (recovery_attempts >= 0),
    ADD COLUMN next_recovery_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN recovery_lease_until TIMESTAMPTZ,
    ADD COLUMN recovery_status VARCHAR(32),
    ADD COLUMN recovery_message VARCHAR(500);

CREATE INDEX idx_payment_refund_recovery_due ON xsy_payment_refund(next_recovery_at, id)
    WHERE deleted = FALSE AND status IN ('CREATED', 'PROCESSING', 'SUCCEEDED');
CREATE INDEX idx_payment_mock_ledger_refund ON xsy_payment_mock_ledger(provider_refund_no)
    WHERE direction = 'OUT';

CREATE TABLE xsy_payment_refund_recovery_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id BIGINT NOT NULL REFERENCES xsy_payment_refund(id),
    operator VARCHAR(64) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    result VARCHAR(32) NOT NULL,
    provider_amount NUMERIC(18, 4),
    detail VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_payment_refund_recovery_log_refund ON xsy_payment_refund_recovery_log(refund_id, id);

CREATE FUNCTION reject_refund_recovery_log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'refund recovery log is append-only';
END;
$$;
CREATE TRIGGER trg_payment_refund_recovery_log_immutable
    BEFORE UPDATE OR DELETE ON xsy_payment_refund_recovery_log
    FOR EACH ROW EXECUTE FUNCTION reject_refund_recovery_log_change();

COMMENT ON TABLE xsy_payment_refund_recovery_log IS '退款查单、补偿与人工恢复的追加审计记录';
COMMENT ON COLUMN xsy_payment_refund.recovery_lease_until IS '渠道查询及幂等派发租约，过期后允许恢复';
