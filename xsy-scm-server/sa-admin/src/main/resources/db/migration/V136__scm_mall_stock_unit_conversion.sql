-- 一种销售单位可以按仓库当前锁定的记账单位选择换算配置；订单确认时冻结所用关系。
CREATE TABLE xsy_product_sku_stock_conversion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id BIGINT NOT NULL,
    sale_unit VARCHAR(32) NOT NULL CHECK (btrim(sale_unit) <> ''),
    stock_unit VARCHAR(32) NOT NULL CHECK (btrim(stock_unit) <> ''),
    stock_units_per_sale_unit NUMERIC(18, 4) NOT NULL CHECK (stock_units_per_sale_unit > 0),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    updated_by VARCHAR(64) NOT NULL
);

CREATE UNIQUE INDEX uk_product_sku_stock_conversion_active
    ON xsy_product_sku_stock_conversion(sku_id, sale_unit, stock_unit) WHERE deleted = FALSE;

ALTER TABLE xsy_sales_order_item
    ADD COLUMN mall_stock_unit_snapshot VARCHAR(32),
    ADD COLUMN mall_stock_units_per_sale_unit NUMERIC(18, 4);
ALTER TABLE xsy_sales_order_item
    ADD CONSTRAINT ck_order_item_mall_stock_factor
        CHECK (mall_stock_units_per_sale_unit IS NULL OR mall_stock_units_per_sale_unit > 0);

ALTER TABLE xsy_inventory_outbound_item
    ADD COLUMN stock_quantity NUMERIC(18, 4);

COMMENT ON COLUMN xsy_sales_order_item.mall_stock_units_per_sale_unit IS '商城订单确认时冻结的库存记账量/1销售单位；历史订单为空';
COMMENT ON COLUMN xsy_inventory_outbound_item.stock_quantity IS '商城自动出库在库存记账单位中的数量；quantity 仍是订单销售单位的实发量';
