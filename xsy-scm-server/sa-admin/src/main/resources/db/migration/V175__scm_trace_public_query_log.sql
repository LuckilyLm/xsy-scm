-- 公开扫码查询审计。
--
-- 扫码页免登录，所以「谁在查、查了多少次」只能靠这张表回答。用途有两个：
-- 发现按 token 枚举的爬取，以及在客户投诉某批货时证明「这个码确实被扫过」。
--
-- 只追加，不参与任何业务判定：查询失败不影响扫码结果，写入异常在服务层吞掉。
-- 不保存完整 User-Agent（长度不可控），只留前 200 字符用于粗分设备类型。

CREATE TABLE xsy_trace_public_query (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id      BIGINT      NOT NULL,
    public_token VARCHAR(32) NOT NULL,
    client_ip    VARCHAR(64),
    user_agent   VARCHAR(200),
    queried_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_trace_public_query_token_not_blank CHECK (length(btrim(public_token)) > 0)
);

CREATE INDEX idx_trace_public_query_token ON xsy_trace_public_query (public_token, queried_at DESC);
CREATE INDEX idx_trace_public_query_time ON xsy_trace_public_query (queried_at DESC);

COMMENT ON TABLE xsy_trace_public_query IS '公开扫码查询审计：只追加，用于发现枚举爬取与举证';
COMMENT ON COLUMN xsy_trace_public_query.client_ip IS '取 X-Forwarded-For 首个地址；为空表示无法判定来源';
COMMENT ON COLUMN xsy_trace_public_query.user_agent IS '只留前 200 字符，用于粗分设备类型';
