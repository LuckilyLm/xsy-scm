-- 采购收货批次（一期只落 L1 批次；包装码 / 一物一码二期再做）。
--
-- 批次是**独立子账**：总账 xsy_inventory_balance 仍按仓库 + 商品规格唯一，批次余额并存为子账，
-- 不变量是「同仓同商品同单位下，各批次余额之和等于总账余额」。不把总账按批次拆行，
-- 因为总账唯一键 (warehouse_id, sku_id) 被现有全部读写路径依赖。
--
-- 批次流水只追加：更正只能追加补偿流水，与库存流水既有约定一致。

ALTER TABLE xsy_warehouse ADD COLUMN lot_tracking_enabled BOOLEAN NOT NULL DEFAULT FALSE;
COMMENT ON COLUMN xsy_warehouse.lot_tracking_enabled IS '是否启用批次追踪；只在新建空仓时开启，开启后不可关闭';

CREATE SEQUENCE trace_lot_no_seq;

CREATE TABLE xsy_trace_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_no VARCHAR(32) NOT NULL,
    source_lot_no VARCHAR(64),
    supplier_id BIGINT,
    sku_id BIGINT NOT NULL,
    origin_type VARCHAR(24) NOT NULL DEFAULT 'PURCHASE_RECEIPT',
    first_receipt_item_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_trace_lot_no UNIQUE (lot_no),
    CONSTRAINT ck_trace_lot_origin CHECK (origin_type IN ('PURCHASE_RECEIPT'))
);
CREATE INDEX idx_trace_lot_sku ON xsy_trace_lot(sku_id, id);
CREATE INDEX idx_trace_lot_source ON xsy_trace_lot(supplier_id, source_lot_no);
COMMENT ON TABLE xsy_trace_lot IS '追溯批次档案：内部批次号由系统发号，来源生产批号原样保存且允许为空';
COMMENT ON COLUMN xsy_trace_lot.source_lot_no IS '供应商或现场提供的来源批号，不参与唯一约束，不冒充内部批次号';

CREATE TABLE xsy_purchase_receipt_item_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_receipt_item_id BIGINT NOT NULL,
    lot_id BIGINT NOT NULL,
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_purchase_receipt_item_lot UNIQUE (purchase_receipt_item_id, lot_id)
);
CREATE INDEX idx_purchase_receipt_item_lot_lot ON xsy_purchase_receipt_item_lot(lot_id);
COMMENT ON TABLE xsy_purchase_receipt_item_lot IS '收货行登记的批次事实：同一行的批次数量之和必须等于本次收货量，由命令校验';

CREATE TABLE xsy_inventory_lot_balance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    lot_id BIGINT NOT NULL,
    unit VARCHAR(32) NOT NULL,
    quantity NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT uk_inventory_lot_balance UNIQUE (warehouse_id, sku_id, lot_id)
);
CREATE INDEX idx_inventory_lot_balance_sku ON xsy_inventory_lot_balance(warehouse_id, sku_id, lot_id);
COMMENT ON TABLE xsy_inventory_lot_balance IS '批次余额子账：只记数量与单位，成本仍按仓库 + 商品规格的平均成本';

CREATE TABLE xsy_inventory_lot_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    lot_id BIGINT NOT NULL,
    movement_type VARCHAR(32) NOT NULL,
    source_document_type VARCHAR(32) NOT NULL,
    source_document_id BIGINT NOT NULL,
    source_document_item_id BIGINT,
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity <> 0),
    unit_snapshot VARCHAR(32) NOT NULL,
    before_quantity NUMERIC(18,4) NOT NULL CHECK (before_quantity >= 0),
    after_quantity NUMERIC(18,4) NOT NULL CHECK (after_quantity >= 0),
    occurred_at TIMESTAMPTZ NOT NULL,
    operator VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT ck_inventory_lot_movement_math CHECK (before_quantity + quantity = after_quantity)
);
CREATE INDEX idx_inventory_lot_movement_lot ON xsy_inventory_lot_movement(lot_id, id);
CREATE INDEX idx_inventory_lot_movement_sku ON xsy_inventory_lot_movement(warehouse_id, sku_id, occurred_at DESC);
COMMENT ON TABLE xsy_inventory_lot_movement IS '批次流水：正数入库、负数出库，只追加，禁止改写或删除';
COMMENT ON COLUMN xsy_inventory_lot_movement.quantity IS '有符号数量：入库为正、出库为负，与 before/after 构成恒等式';

CREATE FUNCTION xsy_reject_inventory_lot_movement_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'inventory lot movements are append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER trg_inventory_lot_movement_append_only BEFORE UPDATE OR DELETE OR TRUNCATE
    ON xsy_inventory_lot_movement FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_inventory_lot_movement_mutation();

