CREATE TABLE xsy_product_bundle_component (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_sku_id BIGINT NOT NULL,
    component_sku_id BIGINT NOT NULL,
    quantity_per_bundle_sale_unit NUMERIC(18, 4) NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64), updated_by VARCHAR(64),
    CONSTRAINT ck_bundle_component_positive CHECK (quantity_per_bundle_sale_unit > 0),
    CONSTRAINT ck_bundle_component_not_self CHECK (bundle_sku_id <> component_sku_id),
    CONSTRAINT ck_bundle_component_version CHECK (version >= 0)
);
CREATE UNIQUE INDEX uk_product_bundle_component_active
    ON xsy_product_bundle_component(bundle_sku_id, component_sku_id) WHERE deleted = FALSE;
CREATE INDEX idx_product_bundle_component_child
    ON xsy_product_bundle_component(component_sku_id) WHERE deleted = FALSE;

CREATE TABLE xsy_order_bundle_component (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    bundle_sku_id BIGINT NOT NULL,
    component_sku_id BIGINT NOT NULL,
    component_sku_code_snapshot VARCHAR(64) NOT NULL,
    component_product_name_snapshot VARCHAR(200) NOT NULL,
    component_sale_unit_snapshot VARCHAR(32) NOT NULL,
    component_stock_unit_snapshot VARCHAR(32) NOT NULL,
    quantity_per_bundle_sale_unit NUMERIC(18, 4) NOT NULL,
    stock_units_per_component_sale_unit NUMERIC(18, 4) NOT NULL,
    component_sale_quantity_snapshot NUMERIC(18, 4) NOT NULL,
    market_unit_price_snapshot NUMERIC(18, 4) NOT NULL,
    market_reference_amount_snapshot NUMERIC(36, 8) NOT NULL,
    allocated_sale_amount_snapshot NUMERIC(18, 4) NOT NULL,
    product_bundle_component_id BIGINT NOT NULL,
    product_bundle_component_version INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    CONSTRAINT ck_order_bundle_qty CHECK (quantity_per_bundle_sale_unit > 0
        AND stock_units_per_component_sale_unit > 0
        AND component_sale_quantity_snapshot > 0 AND market_unit_price_snapshot > 0
        AND market_reference_amount_snapshot > 0 AND allocated_sale_amount_snapshot >= 0)
);
CREATE UNIQUE INDEX uk_order_bundle_component
    ON xsy_order_bundle_component(order_item_id, component_sku_id);
CREATE INDEX idx_order_bundle_component_order ON xsy_order_bundle_component(order_id);

CREATE FUNCTION xsy_reject_order_bundle_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'order bundle snapshot is immutable' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER trg_order_bundle_immutable
    BEFORE UPDATE OR DELETE OR TRUNCATE ON xsy_order_bundle_component
    FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_order_bundle_mutation();

ALTER TABLE xsy_inventory_outbound_item
    ADD COLUMN bundle_component_id BIGINT,
    ADD COLUMN bundle_sale_quantity NUMERIC(18, 4);
ALTER TABLE xsy_inventory_outbound_item ADD CONSTRAINT ck_outbound_bundle_sale_quantity
    CHECK ((bundle_component_id IS NULL AND bundle_sale_quantity IS NULL)
        OR (bundle_component_id IS NOT NULL AND bundle_sale_quantity > 0));
CREATE UNIQUE INDEX uk_outbound_bundle_component
    ON xsy_inventory_outbound_item(outbound_id, bundle_component_id)
    WHERE bundle_component_id IS NOT NULL AND deleted = FALSE;

ALTER TABLE xsy_order_return_receipt_item
    ADD COLUMN bundle_component_id BIGINT,
    ADD COLUMN bundle_receipt_counted BOOLEAN NOT NULL DEFAULT TRUE;
CREATE INDEX idx_return_receipt_bundle_component
    ON xsy_order_return_receipt_item(bundle_component_id)
    WHERE bundle_component_id IS NOT NULL;
