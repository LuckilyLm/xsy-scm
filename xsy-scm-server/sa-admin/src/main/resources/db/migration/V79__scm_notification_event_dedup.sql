CREATE TABLE scm_notification_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key VARCHAR(200) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    receiver_user_type INTEGER NOT NULL,
    receiver_user_id BIGINT NOT NULL,
    data_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    CONSTRAINT uk_scm_notification_event_key UNIQUE (event_key)
);
CREATE INDEX idx_scm_notification_event_receiver ON scm_notification_event (receiver_user_type, receiver_user_id, created_at DESC);
