-- 采购价变更审计：补价与改价都是 append-only 事实，不覆盖历史。
--
-- 为什么单独一张表：操作日志的 before/after 是 JSONB 快照，适合回答「谁在什么时候改了什么」，
-- 但不适合按月统计涨跌、或回答某一行价格被改过几次。价格是供应商对账的依据，需要一条可查询的明细链。
--
-- 幂等：补价/改价命令带 Idempotency-Key，重放命中唯一索引，不会写第二条同等事实。

CREATE TABLE xsy_purchase_price_adjust (
    id                      BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id       BIGINT        NOT NULL,
    purchase_order_item_id  BIGINT        NOT NULL,
    sku_id                  BIGINT        NOT NULL,
    old_price               NUMERIC(18,4),
    new_price               NUMERIC(18,4) NOT NULL,
    -- MANUAL 人工补价/改价；AUTO_LAST_PRICE 超窗口按最近已提交价回填
    source                  VARCHAR(24)   NOT NULL,
    reason                  VARCHAR(500),
    operator                VARCHAR(64)   NOT NULL,
    idempotency_key         VARCHAR(64),
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_purchase_price_adjust_source CHECK (source IN ('MANUAL', 'AUTO_LAST_PRICE')),
    CONSTRAINT ck_purchase_price_adjust_new CHECK (new_price >= 0),
    CONSTRAINT ck_purchase_price_adjust_old CHECK (old_price IS NULL OR old_price >= 0),
    CONSTRAINT ck_purchase_price_adjust_operator CHECK (btrim(operator) <> '')
);

CREATE INDEX idx_purchase_price_adjust_item
    ON xsy_purchase_price_adjust (purchase_order_item_id, created_at DESC);
CREATE INDEX idx_purchase_price_adjust_order
    ON xsy_purchase_price_adjust (purchase_order_id, created_at DESC);
CREATE UNIQUE INDEX uk_purchase_price_adjust_idempotent
    ON xsy_purchase_price_adjust (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

COMMENT ON TABLE xsy_purchase_price_adjust IS '采购价补录/调整审计（append-only）；旧价可为空表示该行此前待定价';
COMMENT ON COLUMN xsy_purchase_price_adjust.source IS 'MANUAL 人工 / AUTO_LAST_PRICE 超窗口按最近已提交价自动回填';
COMMENT ON COLUMN xsy_purchase_price_adjust.idempotency_key IS '命令幂等键；重放命中唯一索引，不写第二条事实';
