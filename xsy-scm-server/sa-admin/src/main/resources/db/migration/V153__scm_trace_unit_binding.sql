-- 分拣扫码绑定：把包装码绑到「分拣任务行」。
--
-- 为什么绑分拣行而不是出库行：分拣行上有客户与订单快照，扫码发生在装箱现场，出库单要到发车才生成。
-- 一码一物：一个包装码只能绑一次，绑错只能作废该码（追加事件），不能改绑。

ALTER TABLE xsy_trace_event DROP CONSTRAINT ck_trace_event_type;
ALTER TABLE xsy_trace_event ADD CONSTRAINT ck_trace_event_type
    CHECK (event_type IN ('ISSUE', 'VOID', 'BIND'));

CREATE TABLE xsy_trace_unit_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    lot_id BIGINT NOT NULL,
    sorting_task_id BIGINT NOT NULL,
    sorting_task_item_id BIGINT NOT NULL,
    sales_order_id BIGINT,
    sales_order_item_id BIGINT,
    customer_id BIGINT,
    customer_name_snapshot VARCHAR(150),
    order_no_snapshot VARCHAR(64),
    bound_at TIMESTAMPTZ NOT NULL,
    bound_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL,
    CONSTRAINT uk_trace_unit_binding_unit UNIQUE (unit_id)
);
CREATE INDEX idx_trace_unit_binding_task_item ON xsy_trace_unit_binding(sorting_task_item_id);
COMMENT ON TABLE xsy_trace_unit_binding IS '包装码与分拣任务行的绑定：一码一物，只能绑一次，绑错只能作废该码';
COMMENT ON COLUMN xsy_trace_unit_binding.customer_name_snapshot IS '绑定时刻的客户名称快照：客户改名后仍能回答「当时发给了谁」';

CREATE FUNCTION xsy_reject_trace_unit_binding_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'trace unit bindings are append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER trg_trace_unit_binding_append_only BEFORE UPDATE OR DELETE OR TRUNCATE
    ON xsy_trace_unit_binding FOR EACH STATEMENT EXECUTE FUNCTION xsy_reject_trace_unit_binding_mutation();

