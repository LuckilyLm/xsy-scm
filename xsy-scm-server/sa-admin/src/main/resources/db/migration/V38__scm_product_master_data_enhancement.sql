-- ---------------------------------------------------------------------------
-- Step 3: 商品标签
-- ---------------------------------------------------------------------------
CREATE TABLE product_tag
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_code   VARCHAR(64) NOT NULL,
    name       VARCHAR(64) NOT NULL,
    status     VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    sort_order INTEGER     NOT NULL DEFAULT 0,
    version    INTEGER     NOT NULL DEFAULT 0,
    deleted    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_product_tag_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_product_tag_version CHECK (version >= 0)
);
CREATE UNIQUE INDEX uk_product_tag_code_active ON product_tag (tag_code) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_product_tag_name_active ON product_tag (name) WHERE deleted = FALSE;
CREATE INDEX idx_product_tag_status ON product_tag (status) WHERE deleted = FALSE;

COMMENT ON TABLE product_tag IS '商品标签字典（有机 / 进口 / 学校专供等），用于列表筛选与后续商城、采购、报表';
COMMENT ON COLUMN product_tag.status IS 'ENABLED 可继续打标 / DISABLED 只保留历史关系，不再出现在可选标签里';

CREATE TABLE product_tag_relation
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spu_id     BIGINT      NOT NULL,
    tag_id     BIGINT      NOT NULL,
    version    INTEGER     NOT NULL DEFAULT 0,
    deleted    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_product_tag_relation_version CHECK (version >= 0)
);
-- 同一商品同一标签只能有一条活动关系；ON CONFLICT 目标与本索引逐字一致（Q11）。
CREATE UNIQUE INDEX uk_product_tag_relation_active ON product_tag_relation (spu_id, tag_id) WHERE deleted = FALSE;
CREATE INDEX idx_product_tag_relation_tag_id ON product_tag_relation (tag_id) WHERE deleted = FALSE;
CREATE INDEX idx_product_tag_relation_spu_id ON product_tag_relation (spu_id) WHERE deleted = FALSE;

COMMENT ON TABLE product_tag_relation IS '商品 SPU 与标签的多对多关系，打标入口在商品档案与批量维护';
COMMENT ON COLUMN product_tag_relation.spu_id IS '商品 SPU id，无外键，完整性由应用层保证';
COMMENT ON COLUMN product_tag_relation.tag_id IS '标签 id，无外键，标签被引用后禁止删除';
