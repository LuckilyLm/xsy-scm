-- SDP-04 电子秤设备接入：设备绑定、员工授权会话、任务领取租约。
--
-- 边界（见 docs/sohe-scale-integration-handoff.md 与 docs/decisions.md）：
--   * 设备身份与员工身份分离。设备凭证只证明「哪台秤」，不携带订单、库存、财务权限；
--     员工授权会话只证明「谁在操作」，两者都通过才允许写业务。
--   * 本迁移只建立身份与租约，不改变任何分拣数量语义。正式分拣仍只经
--     SortingTaskService.enter 写入，设备事件本身不代表已确认。
--   * 不新增数据库外键：跨对象关联由领域服务在同一事务内校验（V109 已确立）。
--   * 配对码与凭证只存摘要，明文仅在签发时返回一次，避免库内泄露即可冒充设备。

CREATE TABLE xsy_scale_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code VARCHAR(64) NOT NULL CHECK (btrim(device_code) <> ''),
    device_name VARCHAR(100),
    device_model VARCHAR(100),
    warehouse_id BIGINT NOT NULL,
    station_code VARCHAR(64),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_ACTIVATION'
        CHECK (status IN ('PENDING_ACTIVATION', 'ACTIVE', 'SUSPENDED', 'REVOKED')),
    protocol_type VARCHAR(40),
    agent_version VARCHAR(40),
    -- 一次性配对码摘要；激活成功即清空，不能重放。
    pairing_code_hash VARCHAR(128),
    pairing_expires_at TIMESTAMPTZ,
    -- 设备凭证摘要；轮换时替换，旧值立即失效。
    credential_hash VARCHAR(128),
    credential_expires_at TIMESTAMPTZ,
    last_seen_at TIMESTAMPTZ,
    last_reading_at TIMESTAMPTZ,
    -- 设备自报的待同步事件数，仅作运维观测，不作为「没有遗漏」的证据。
    queue_depth INTEGER CHECK (queue_depth IS NULL OR queue_depth >= 0),
    scale_connected BOOLEAN,
    printer_connected BOOLEAN,
    revoked_at TIMESTAMPTZ,
    revoked_by VARCHAR(64),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64),
    updated_by VARCHAR(64)
);

-- 设备编号是外部可见标识，必须全局唯一；解绑不释放编号，避免历史读数指向另一台秤。
CREATE UNIQUE INDEX uk_scale_device_code ON xsy_scale_device (device_code) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_scale_device_credential ON xsy_scale_device (credential_hash)
    WHERE credential_hash IS NOT NULL;
CREATE INDEX idx_scale_device_warehouse ON xsy_scale_device (warehouse_id, status) WHERE deleted = FALSE;

COMMENT ON TABLE xsy_scale_device IS '电子秤设备绑定与凭证状态；解绑后保留历史读数归属，不物理删除';
COMMENT ON COLUMN xsy_scale_device.device_code IS '外部设备编号，全局唯一；解绑不释放，防止历史读数被另一台秤继承';
COMMENT ON COLUMN xsy_scale_device.warehouse_id IS '绑定仓库；设备可见任务不超出该仓库，跨对象由领域服务校验，不建外键';
COMMENT ON COLUMN xsy_scale_device.status IS 'PENDING_ACTIVATION 待激活 / ACTIVE 已激活 / SUSPENDED 已暂停 / REVOKED 已撤销';
COMMENT ON COLUMN xsy_scale_device.pairing_code_hash IS '一次性配对码摘要；激活成功后清空，明文只在发码时返回一次';
COMMENT ON COLUMN xsy_scale_device.credential_hash IS '设备访问凭证摘要；轮换即替换，不保存明文';
COMMENT ON COLUMN xsy_scale_device.queue_depth IS '设备自报待同步数，仅运维观测；不能据此推断云端无遗漏';
COMMENT ON COLUMN xsy_scale_device.version IS '乐观锁版本，设备配置变更与解绑都要求版本一致';

CREATE TABLE xsy_scale_device_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    -- 秤端请求头 X-Operator-Session 携带的令牌摘要；服务端据此解析真实员工，
    -- 客户端不得自报员工 ID，否则可伪造成任意员工做分拣确认。
    session_token_hash VARCHAR(128) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    end_reason VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(64),
    CONSTRAINT ck_scale_device_session_expiry CHECK (expires_at > issued_at),
    CONSTRAINT ck_scale_device_session_end CHECK (ended_at IS NULL OR ended_at >= issued_at)
);

CREATE UNIQUE INDEX uk_scale_device_session_token ON xsy_scale_device_session (session_token_hash);
CREATE INDEX idx_scale_device_session_device ON xsy_scale_device_session (device_id, expires_at DESC);
CREATE INDEX idx_scale_device_session_employee ON xsy_scale_device_session (employee_id, expires_at DESC);

COMMENT ON TABLE xsy_scale_device_session IS '设备上的员工授权会话；把「哪台秤」与「谁在操作」分开记录，业务写入记真实员工';
COMMENT ON COLUMN xsy_scale_device_session.device_id IS '关联 xsy_scale_device.id；不建外键，由领域服务校验';
COMMENT ON COLUMN xsy_scale_device_session.employee_id IS '关联 t_employee.id；业务写入的 accepted_by / sorted_by 取该员工';
COMMENT ON COLUMN xsy_scale_device_session.session_token_hash IS '秤端 X-Operator-Session 的令牌摘要；不接受客户端自报员工 ID';
COMMENT ON COLUMN xsy_scale_device_session.ended_at IS '会话结束时间；结束原因写入 end_reason，不删除历史';

CREATE TABLE xsy_scale_job_lease (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    -- 领取时的任务版本。任务被改派或重开导致版本变化时，旧租约不能继续写业务。
    task_version INTEGER NOT NULL CHECK (task_version >= 0),
    leased_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    release_reason VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_scale_job_lease_expiry CHECK (expires_at > leased_at),
    CONSTRAINT ck_scale_job_lease_release CHECK (released_at IS NULL OR released_at >= leased_at)
);

-- 同一任务同时只允许一个有效租约：两台秤抢同一任务必须由服务端仲裁，
-- 不能仅靠设备端禁用按钮。
CREATE UNIQUE INDEX uk_scale_job_lease_active_task ON xsy_scale_job_lease (task_id)
    WHERE released_at IS NULL;
CREATE INDEX idx_scale_job_lease_device ON xsy_scale_job_lease (device_id, expires_at DESC);
CREATE INDEX idx_scale_job_lease_employee ON xsy_scale_job_lease (employee_id, expires_at DESC);

COMMENT ON TABLE xsy_scale_job_lease IS '秤端领取分拣任务的工作租约；同一任务同时只能有一个有效租约';
COMMENT ON COLUMN xsy_scale_job_lease.session_id IS '关联 xsy_scale_device_session.id；租约失效后不能继续写业务';
COMMENT ON COLUMN xsy_scale_job_lease.task_version IS '领取时的任务版本；改派或重开后版本变化，旧租约必须重新领取';
COMMENT ON COLUMN xsy_scale_job_lease.released_at IS '释放时间；为空表示租约仍有效，部分唯一索引据此仲裁并发领取';
