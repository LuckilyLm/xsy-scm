-- SDP-03 分次分拣是追加审计事实；最终分拣数量仍由 task_item 的确认命令写入。
-- 不放宽原有“结果与分拣量成对出现”约束；未确认分次只在本表累积。
CREATE TABLE xsy_sorting_part_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    task_item_id BIGINT NOT NULL,
    event_type VARCHAR(16) NOT NULL,
    quantity_delta NUMERIC(18,4) NOT NULL,
    total_quantity NUMERIC(18,4) NOT NULL,
    note VARCHAR(500),
    created_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_sorting_part_record_event CHECK (event_type IN ('APPEND', 'SET_TOTAL')),
    CONSTRAINT ck_sorting_part_record_delta CHECK (event_type <> 'APPEND' OR quantity_delta > 0),
    CONSTRAINT ck_sorting_part_record_total CHECK (total_quantity >= 0)
);
CREATE INDEX idx_sorting_part_record_task ON xsy_sorting_part_record (task_id, id DESC);
CREATE INDEX idx_sorting_part_record_item ON xsy_sorting_part_record (task_item_id, id DESC);
COMMENT ON TABLE xsy_sorting_part_record IS '分次分拣追加事件与最终数量校正审计；不直接代表可发车数量';
COMMENT ON COLUMN xsy_sorting_part_record.quantity_delta IS 'APPEND 为分次新增量，SET_TOTAL 为本次总量调整的有符号差值';
COMMENT ON COLUMN xsy_sorting_part_record.total_quantity IS '事件发生后的分次累计量；最终出库仍取已完成任务明细的正式结果';
