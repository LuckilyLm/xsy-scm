-- 单号不复用：唯一性覆盖软删行，与订单/收货单编号口径一致。
CREATE UNIQUE INDEX uk_sorting_task_no ON sorting_task(task_no);
-- 数据范围谓词：授权仓 ∩ 受指派人，状态用于「我的待办」过滤。
CREATE INDEX idx_sorting_task_scope ON sorting_task(warehouse_id,assignee_employee_id,status) WHERE deleted=FALSE;
-- 裁决第 2 条：一条订单行只能被一条活动明细占用；重复生成任务在此处兜底。
CREATE UNIQUE INDEX uk_sorting_task_item_active_line ON sorting_task_item(sales_order_item_id)
 WHERE deleted=FALSE AND occupation_status='ACTIVE';
CREATE INDEX idx_sorting_task_item_task ON sorting_task_item(task_id) WHERE deleted=FALSE;
-- 配送资格按订单聚合判定（补充第 18 条），需要按订单快速取到全部明细。
CREATE INDEX idx_sorting_task_item_order ON sorting_task_item(sales_order_id) WHERE deleted=FALSE;
-- 按商品汇总视角：按 SKU + 单位分组，不跨单位求和。
CREATE INDEX idx_sorting_task_item_sku ON sorting_task_item(sku_id,sale_unit_snapshot) WHERE deleted=FALSE;
