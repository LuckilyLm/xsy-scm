-- P1 分拣管理数据地基：分拣任务与任务明细。裁决依据 docs/decisions.md
-- 「P1 分拣管理裁决（2026-09-24）」第 1、2、3、8、9、16、17 条与补充第 15–20 条。
--
-- 边界（越界即违反裁决）：
--   * 分拣只写自己这两张表：不动 sales_order_item 的 actual_quantity / settlement_*，
--     不写 inventory_balance / inventory_movement，不创建出库单，也不移动预留触发点。
--   * 计划量是**进入分拣那一刻冻结的快照**，取自订单行的 actual_quantity；
--     标品在提交时按订购量落值、非标在确认前必须已录实重，因此 CONFIRMED 订单的
--     有效行必然 > 0，本表据此把快照定为 NOT NULL 且 > 0。
--   * 一条订单行最多被一条**活动**明细占用：占用位写在明细行自己身上
--     （与 delivery_route_order.assignment_status 同形态），因此部分唯一索引不需要跨表判断。
--     取消任务与置明细 RELEASED 必须在同一事务里完成，这是索引与任务状态不漂移的唯一前提。
--   * 无外键（项目级口径），关系完整性由服务层与下列 CHECK / 唯一索引共同保证。
CREATE SEQUENCE sorting_task_no_seq;

CREATE TABLE sorting_task (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_no VARCHAR(40) NOT NULL CHECK(btrim(task_no)<>''),
 warehouse_id BIGINT NOT NULL,
 warehouse_name_snapshot VARCHAR(100) NOT NULL CHECK(btrim(warehouse_name_snapshot)<>''),
 assignee_employee_id BIGINT,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
   CHECK(status IN ('PENDING','SORTING','COMPLETED','CANCELLED')),
 remark VARCHAR(500),
 started_at TIMESTAMPTZ,
 completed_at TIMESTAMPTZ,
 cancelled_at TIMESTAMPTZ,
 print_count INTEGER NOT NULL DEFAULT 0 CHECK(print_count>=0),
 last_printed_at TIMESTAMPTZ,
 last_printed_by VARCHAR(64),
 version INTEGER NOT NULL DEFAULT 0 CHECK(version>=0), deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 created_by VARCHAR(64), updated_by VARCHAR(64)
);

CREATE TABLE sorting_task_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL,
 sales_order_id BIGINT NOT NULL,
 sales_order_item_id BIGINT NOT NULL,
 order_no_snapshot VARCHAR(40) NOT NULL,
 customer_id BIGINT NOT NULL,
 customer_name_snapshot VARCHAR(100) NOT NULL,
 spu_id BIGINT NOT NULL,
 sku_id BIGINT NOT NULL,
 spu_code_snapshot VARCHAR(64),
 product_name_snapshot VARCHAR(200) NOT NULL,
 sku_code_snapshot VARCHAR(64),
 spec_name_snapshot VARCHAR(100),
 sale_unit_snapshot VARCHAR(32) NOT NULL,
 product_type_snapshot VARCHAR(16) NOT NULL
   CHECK(product_type_snapshot IN ('STANDARD','NON_STANDARD')),
 planned_quantity_snapshot NUMERIC(18,4) NOT NULL CHECK(planned_quantity_snapshot>0),
 sorted_quantity NUMERIC(18,4) CHECK(sorted_quantity IS NULL OR sorted_quantity>=0),
 result VARCHAR(20) CHECK(result IS NULL OR result IN ('NORMAL','SHORT','OUT_OF_STOCK','OVER')),
 reason VARCHAR(500),
 sorted_by VARCHAR(64),
 sorted_at TIMESTAMPTZ,
 occupation_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
   CHECK(occupation_status IN ('ACTIVE','RELEASED')),
 version INTEGER NOT NULL DEFAULT 0 CHECK(version>=0), deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 created_by VARCHAR(64), updated_by VARCHAR(64),
 -- 结果与分拣量成对出现：只有「未处理」和「已处理」两态，不存在有量无结果或有结果无量。
 CONSTRAINT ck_sorting_task_item_processed_pairing CHECK
  ((result IS NULL AND sorted_quantity IS NULL) OR (result IS NOT NULL AND sorted_quantity IS NOT NULL)),
 -- 任何与计划量不一致的结果都要写原因（P1 不设容差阈值，也没有自动重新结算）。
 CONSTRAINT ck_sorting_task_item_diff_reason CHECK
  (result IS NULL OR result = 'NORMAL' OR btrim(COALESCE(reason,''))<>'')
);

