-- 客户分组价：客户按分组维护协议价，组内对同一商品、同一计量单位执行同一价格。
--
-- 为什么单独建表，而不是把协议价改成按分组：
--   * 客户协议价（xsy_customer_agreement_price）是逐客约定，仍是个别客户的例外通道；
--   * 分组价按「分组 + 商品 + 销售单位」维护，商品下同一单位的规格自动共享，不需要逐规格录入；
--   * 两者价格来源不同（CUSTOMER_GROUP / AGREEMENT），订单行要能解释价格从哪来。
--
-- 分组必须至少有一个客户，否则这条分组价永远不会被解析到；约束由应用层在保存时校验。
-- 客户分组与客户类型（个人 / 公司 / 集团）无关，客户类型不参与定价。

CREATE TABLE xsy_customer_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_code VARCHAR(32) NOT NULL,
    group_name VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_group_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_customer_group_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_customer_group_code ON xsy_customer_group (group_code)
    WHERE deleted = FALSE;

ALTER TABLE xsy_customer
    ADD COLUMN customer_group_id BIGINT REFERENCES xsy_customer_group (id);

CREATE INDEX idx_customer_group ON xsy_customer (customer_group_id)
    WHERE deleted = FALSE AND customer_group_id IS NOT NULL;

CREATE TABLE xsy_customer_group_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES xsy_customer_group (id),
    spu_id BIGINT NOT NULL,
    sale_unit VARCHAR(32) NOT NULL,
    unit_price NUMERIC(18, 4) NOT NULL,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_group_price_amount CHECK (unit_price >= 0),
    CONSTRAINT ck_customer_group_price_unit CHECK (btrim(sale_unit) <> ''),
    CONSTRAINT ck_customer_group_price_period CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT ck_customer_group_price_version CHECK (version >= 0)
);

-- 同一分组、商品、单位、开始时刻只允许一条；时间重叠由应用层在事务内判定。
CREATE UNIQUE INDEX uk_customer_group_price_start
    ON xsy_customer_group_price (group_id, spu_id, sale_unit, effective_from)
    WHERE deleted = FALSE;

CREATE INDEX idx_customer_group_price_lookup
    ON xsy_customer_group_price (group_id, spu_id, sale_unit)
    WHERE deleted = FALSE;

CREATE TABLE xsy_customer_group_price_operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_price_id BIGINT NOT NULL,
    operation_type VARCHAR(20) NOT NULL,
    operator VARCHAR(64) NOT NULL,
    before_data JSONB,
    after_data JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    CONSTRAINT ck_customer_group_price_log_operation CHECK (operation_type IN ('CREATE', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_customer_group_price_log_before CHECK (before_data IS NULL OR jsonb_typeof(before_data) = 'object'),
    CONSTRAINT ck_customer_group_price_log_after CHECK (after_data IS NULL OR jsonb_typeof(after_data) = 'object')
);

CREATE INDEX idx_customer_group_price_log_price
    ON xsy_customer_group_price_operation_log (group_price_id, created_at DESC);

-- 订单行价格来源放开到 CUSTOMER_GROUP：下单与锁价都要能记录这个来源。
ALTER TABLE xsy_sales_order_item DROP CONSTRAINT IF EXISTS ck_sales_order_item_draft_source;
ALTER TABLE xsy_sales_order_item
    ADD CONSTRAINT ck_sales_order_item_draft_source
        CHECK (draft_price_source IN
               ('AGREEMENT', 'CUSTOMER_GROUP', 'CUSTOMER_TYPE', 'TIME_PRICE', 'MARKET', 'OVERRIDE'));

ALTER TABLE xsy_sales_order_item DROP CONSTRAINT IF EXISTS ck_sales_order_item_locked_source;
ALTER TABLE xsy_sales_order_item
    ADD CONSTRAINT ck_sales_order_item_locked_source
        CHECK (locked_price_source IS NULL
            OR locked_price_source IN
               ('AGREEMENT', 'CUSTOMER_GROUP', 'CUSTOMER_TYPE', 'TIME_PRICE', 'MARKET', 'OVERRIDE'));

