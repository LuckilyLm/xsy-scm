                                                                                                  START WITH 1
                                                                                                  INCREMENT BY 1
                                                                                                  NO MINVALUE
                                                                                                  NO MAXVALUE
                                                                                                  CACHE 1),
  event_key varchar(160) CONSTRAINT sorting_scale_event_event_key_not_null NOT NULL,
  task_id bigint CONSTRAINT sorting_scale_event_task_id_not_null NOT NULL,
  task_item_id bigint,
  sku_id bigint,
  device_code varchar(64) CONSTRAINT sorting_scale_event_device_code_not_null NOT NULL,
  raw_reading numeric(18, 4) CONSTRAINT sorting_scale_event_raw_reading_not_null NOT NULL,
  unit varchar(32) CONSTRAINT sorting_scale_event_unit_not_null NOT NULL,
  stable_flag boolean CONSTRAINT sorting_scale_event_stable_flag_not_null NOT NULL,
  captured_at timestamp with time zone CONSTRAINT sorting_scale_event_captured_at_not_null NOT NULL,
  received_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT sorting_scale_event_received_at_not_null NOT NULL,
  status varchar(16) DEFAULT CAST('PENDING' AS varchar) CONSTRAINT sorting_scale_event_status_not_null NOT NULL,
  accepted_quantity numeric(18, 4),
  accepted_at timestamp with time zone,
  accepted_by varchar(64),
  rejected_at timestamp with time zone,
  rejected_by varchar(64),
  reject_reason varchar(200),
  version integer DEFAULT 0 CONSTRAINT sorting_scale_event_version_not_null NOT NULL,
  basket_no integer,
  operation_id varchar(160),
  device_session_id bigint,
  job_version varchar(40),
  task_item_version integer,
  business_unit varchar(32),
  net_weight numeric(18, 4),
  weight_kind varchar(8),
  conversion_rule varchar(32),
  tare_weight numeric(18, 4),
  stability_source varchar(32),
  protocol_type varchar(40),
  agent_version varchar(40),
  completion_id bigint,
  CONSTRAINT ck_sorting_scale_event_accepted CHECK (CAST(status AS text) <> CAST('ACCEPTED' AS text)
                                                 OR (accepted_at IS NOT NULL
                                                 AND accepted_by IS NOT NULL
                                                 AND accepted_quantity IS NOT NULL
                                                 AND task_item_id IS NOT NULL)),
  CONSTRAINT ck_sorting_scale_event_basket_no CHECK (basket_no IS NULL
                                                  OR basket_no > 0),
  CONSTRAINT ck_sorting_scale_event_captured CHECK (captured_at <= received_at + CAST('00:05:00' AS interval)),
  CONSTRAINT ck_sorting_scale_event_net_weight CHECK ((net_weight IS NULL
                                                   AND business_unit IS NULL)
                                                   OR (net_weight IS NOT NULL
                                                   AND business_unit IS NOT NULL
                                                   AND net_weight >= CAST(0 AS numeric))),
  CONSTRAINT ck_sorting_scale_event_reading CHECK (raw_reading >= CAST(0 AS numeric)),
  CONSTRAINT ck_sorting_scale_event_rejected CHECK (CAST(status AS text) <> CAST('REJECTED' AS text)
                                                 OR (rejected_at IS NOT NULL
                                                 AND rejected_by IS NOT NULL)),
  CONSTRAINT ck_sorting_scale_event_status CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'ACCEPTED'::character varying, 'REJECTED'::character varying])::text[]))),
  CONSTRAINT ck_sorting_scale_event_weight_kind CHECK (((weight_kind IS NULL) OR ((weight_kind)::text = ANY ((ARRAY['NET'::character varying, 'GROSS'::character varying])::text[])))),
  CONSTRAINT sorting_scale_event_pkey PRIMARY KEY (id),
  CONSTRAINT uk_sorting_scale_event_key UNIQUE (event_key)
);

