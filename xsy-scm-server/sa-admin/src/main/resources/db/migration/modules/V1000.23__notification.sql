-- 鲜蔬源：notification模块最终结构与默认数据（截至原V244）。
-- 仅用于空库初始化；已有库先通过显式基线切换工具核对并接管。
CREATE SCHEMA IF NOT EXISTS xsy_v2;
SET search_path TO xsy_v2, public;
SET check_function_bodies = false;

CREATE TABLE xsy_v2.xsy_notification_event (
  id bigint CONSTRAINT scm_notification_event_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy_v2.scm_notification_event_id_seq
                                                                                                     START WITH 1
                                                                                                     INCREMENT BY 1
                                                                                                     NO MINVALUE
                                                                                                     NO MAXVALUE
                                                                                                     CACHE 1),
  event_key varchar(200) CONSTRAINT scm_notification_event_event_key_not_null NOT NULL,
  event_type varchar(64) CONSTRAINT scm_notification_event_event_type_not_null NOT NULL,
  receiver_user_type integer CONSTRAINT scm_notification_event_receiver_user_type_not_null NOT NULL,
  receiver_user_id bigint CONSTRAINT scm_notification_event_receiver_user_id_not_null NOT NULL,
  data_id bigint,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT scm_notification_event_created_at_not_null NOT NULL,
  created_by varchar(64),
  CONSTRAINT scm_notification_event_pkey PRIMARY KEY (id),
  CONSTRAINT uk_scm_notification_event_key UNIQUE (event_key)
);

COMMENT ON TABLE xsy_v2.xsy_notification_event
  IS '站内通知事件：记录已发送的通知幂等键与接收人。';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.id
  IS '主键 ID';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.event_key
  IS '事件幂等键';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.event_type
  IS '事件类型';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.receiver_user_type
  IS '接收人用户类型';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.receiver_user_id
  IS '接收人用户 ID';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.data_id
  IS '关联业务数据 ID';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.created_at
  IS '创建时间';

COMMENT ON COLUMN xsy_v2.xsy_notification_event.created_by
  IS '创建人（用户类型:用户 ID）';

CREATE INDEX idx_scm_notification_event_receiver
  ON xsy_v2.xsy_notification_event (receiver_user_type,
                                    receiver_user_id,
                                    created_at DESC);

SELECT pg_catalog.setval('xsy_v2.scm_notification_event_id_seq', 1, FALSE);

SET check_function_bodies = true;
