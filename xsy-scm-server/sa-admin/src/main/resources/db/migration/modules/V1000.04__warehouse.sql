-- 鲜蔬源：warehouse模块最终结构与默认数据（截至原V244）。
-- 仅用于空库初始化；已有库先通过显式基线切换工具核对并接管。
CREATE SCHEMA IF NOT EXISTS xsy_v2;
SET search_path TO xsy_v2, public;
SET check_function_bodies = false;

CREATE SEQUENCE xsy_v2.employee_warehouse_scope_id_seq
  START WITH 1
  INCREMENT BY 1
  NO MINVALUE
  NO MAXVALUE
  CACHE 1;

CREATE SEQUENCE xsy_v2.warehouse_code_seq
  START WITH 1
  INCREMENT BY 1
  NO MINVALUE
  NO MAXVALUE
  CACHE 1;

CREATE TABLE xsy_v2.xsy_employee_warehouse_scope (
  id bigint CONSTRAINT employee_warehouse_scope_id_not_null NOT NULL DEFAULT nextval(CAST('xsy_v2.employee_warehouse_scope_id_seq' AS regclass)),
  employee_id bigint CONSTRAINT employee_warehouse_scope_employee_id_not_null NOT NULL,
  warehouse_id bigint CONSTRAINT employee_warehouse_scope_warehouse_id_not_null NOT NULL,
  deleted_flag boolean DEFAULT FALSE CONSTRAINT employee_warehouse_scope_deleted_flag_not_null NOT NULL,
  create_time timestamp DEFAULT CURRENT_TIMESTAMP CONSTRAINT employee_warehouse_scope_create_time_not_null NOT NULL,
  update_time timestamp DEFAULT CURRENT_TIMESTAMP CONSTRAINT employee_warehouse_scope_update_time_not_null NOT NULL,
  CONSTRAINT ck_employee_warehouse_scope_flag CHECK (deleted_flag = ANY(ARRAY[TRUE, FALSE])),
  CONSTRAINT ck_employee_warehouse_scope_positive CHECK (employee_id > 0
                                                     AND warehouse_id > 0),
  CONSTRAINT employee_warehouse_scope_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE xsy_v2.xsy_employee_warehouse_scope
  IS '员工可操作的仓库授权（SCM 数据范围的仓库维度事实来源，一行=一人一仓）';

COMMENT ON COLUMN xsy_v2.xsy_employee_warehouse_scope.id
  IS '主键';

COMMENT ON COLUMN xsy_v2.xsy_employee_warehouse_scope.employee_id
  IS '员工 id，对应 t_employee.employee_id（无外键，服务层校验）';

COMMENT ON COLUMN xsy_v2.xsy_employee_warehouse_scope.warehouse_id
  IS '仓库 id，对应 warehouse.id（无外键，服务层校验）';

COMMENT ON COLUMN xsy_v2.xsy_employee_warehouse_scope.deleted_flag
  IS '授权回收标识；活动授权受部分唯一索引约束，回收后同一组合可重新授权';

COMMENT ON COLUMN xsy_v2.xsy_employee_warehouse_scope.create_time
  IS '授权建立时间';

COMMENT ON COLUMN xsy_v2.xsy_employee_warehouse_scope.update_time
  IS '最后变更时间';

ALTER SEQUENCE xsy_v2.employee_warehouse_scope_id_seq OWNED BY xsy_v2.xsy_employee_warehouse_scope.id;

CREATE TABLE xsy_v2.xsy_warehouse (
  id bigint CONSTRAINT warehouse_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy_v2.warehouse_id_seq
                                                                                        START WITH 1
                                                                                        INCREMENT BY 1
                                                                                        NO MINVALUE
                                                                                        NO MAXVALUE
                                                                                        CACHE 1),
  warehouse_code varchar(64) CONSTRAINT warehouse_warehouse_code_not_null NOT NULL,
  name varchar(150) CONSTRAINT warehouse_name_not_null NOT NULL,
  status varchar(16) DEFAULT CAST('ENABLED' AS varchar) CONSTRAINT warehouse_status_not_null NOT NULL,
  address varchar(255),
  remark varchar(500),
  version integer DEFAULT 0 CONSTRAINT warehouse_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT warehouse_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT warehouse_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT warehouse_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  province_code integer,
  province_name varchar(32),
  city_code integer,
  city_name varchar(64),
  district_code integer,
  district_name varchar(64),
  longitude numeric(11, 8),
  latitude numeric(10, 8),
  geom_crs varchar(8),
  lot_tracking_enabled boolean DEFAULT FALSE NOT NULL,
  allow_negative_stock boolean DEFAULT FALSE NOT NULL,
  CONSTRAINT ck_warehouse_coordinate_pair CHECK ((longitude IS NULL) = (latitude IS NULL)),
  CONSTRAINT ck_warehouse_crs_with_coordinate CHECK (geom_crs IS NULL
                                                  OR (longitude IS NOT NULL
                                                  AND latitude IS NOT NULL)),
  CONSTRAINT ck_warehouse_geom_crs CHECK (((geom_crs IS NULL) OR ((geom_crs)::text = ANY ((ARRAY['GCJ02'::character varying, 'WGS84'::character varying])::text[])))),
  CONSTRAINT ck_warehouse_latitude CHECK (latitude IS NULL
                                       OR (latitude >= CAST(CAST('-90' AS integer) AS numeric)
                                       AND latitude <= CAST(90 AS numeric))),
  CONSTRAINT ck_warehouse_location_complete CHECK ((((longitude IS NULL) AND (latitude IS NULL) AND (geom_crs IS NULL)) OR ((longitude IS NOT NULL) AND (latitude IS NOT NULL) AND (geom_crs IS NOT NULL) AND ((longitude >= ('-180'::integer)::numeric) AND (longitude <= (180)::numeric)) AND ((latitude >= ('-90'::integer)::numeric) AND (latitude <= (90)::numeric)) AND ((geom_crs)::text = ANY ((ARRAY['GCJ02'::character varying, 'WGS84'::character varying])::text[]))))),
  CONSTRAINT ck_warehouse_longitude CHECK (longitude IS NULL
                                        OR (longitude >= CAST(CAST('-180' AS integer) AS numeric)
                                        AND longitude <= CAST(180 AS numeric))),
  CONSTRAINT ck_warehouse_status CHECK (((status)::text = ANY ((ARRAY['ENABLED'::character varying, 'DISABLED'::character varying])::text[]))),
  CONSTRAINT ck_warehouse_version CHECK (version >= 0),
  CONSTRAINT warehouse_pkey PRIMARY KEY (id)
);

