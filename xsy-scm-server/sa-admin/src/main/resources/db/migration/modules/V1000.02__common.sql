CREATE TABLE xsy_v2.xsy_region (
  id bigint CONSTRAINT scm_region_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy_v2.scm_region_id_seq
                                                                                         START WITH 1
                                                                                         INCREMENT BY 1
                                                                                         NO MINVALUE
                                                                                         NO MAXVALUE
                                                                                         CACHE 1),
  region_code integer CONSTRAINT scm_region_region_code_not_null NOT NULL,
  parent_code integer,
  region_name varchar(64) CONSTRAINT scm_region_region_name_not_null NOT NULL,
  region_level smallint CONSTRAINT scm_region_region_level_not_null NOT NULL,
  center_lng numeric(11, 8),
  center_lat numeric(10, 8),
  version integer DEFAULT 0 CONSTRAINT scm_region_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT scm_region_deleted_not_null NOT NULL,
