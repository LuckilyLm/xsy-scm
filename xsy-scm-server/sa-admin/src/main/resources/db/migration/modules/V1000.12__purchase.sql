CREATE FUNCTION xsy_v2.xsy_guard_purchase_inquiry_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'ACCEPTED' THEN
        RAISE EXCEPTION 'accepted purchase inquiry cannot be changed' USING ERRCODE='23514';
    END IF;
    IF (NEW.batch_id, NEW.warehouse_id, NEW.purchaser_id, NEW.sku_id, NEW.sku_code_snapshot,
        NEW.product_name_snapshot, NEW.demand_unit, NEW.required_quantity, NEW.deadline_at,
        NEW.created_by) IS DISTINCT FROM
       (OLD.batch_id, OLD.warehouse_id, OLD.purchaser_id, OLD.sku_id, OLD.sku_code_snapshot,
        OLD.product_name_snapshot, OLD.demand_unit, OLD.required_quantity, OLD.deadline_at,
        OLD.created_by) THEN
        RAISE EXCEPTION 'purchase inquiry source is immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.status = 'ACCEPTED' AND NOT EXISTS (
        SELECT 1 FROM xsy_purchase_inquiry_quote q
        WHERE q.id = NEW.accepted_quote_id AND q.inquiry_id = NEW.id
    ) THEN
        RAISE EXCEPTION 'selected quote does not belong to inquiry' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;

