-- 商城（小程序）客户身份、会话、收货地址与购物车基础表。
-- 不创建数据库外键，保留唯一约束、检查约束与关系列索引。

CREATE TABLE mall_customer_account
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT       NOT NULL,
    username       VARCHAR(64)  NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    contact_name   VARCHAR(100),
    contact_phone  VARCHAR(32),
    wechat_openid  VARCHAR(64),
    status         VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    last_login_at  TIMESTAMPTZ,
    version        INTEGER      NOT NULL DEFAULT 0,
    deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(64),
    updated_by     VARCHAR(64),
    CONSTRAINT ck_mall_customer_account_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_mall_customer_account_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_mall_customer_account_username_active
    ON mall_customer_account (LOWER(username)) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_mall_customer_account_openid_active
    ON mall_customer_account (wechat_openid) WHERE deleted = FALSE AND wechat_openid IS NOT NULL;
CREATE INDEX idx_mall_customer_account_customer_active
    ON mall_customer_account (customer_id) WHERE deleted = FALSE;

CREATE TABLE mall_customer_session
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT       NOT NULL,
    customer_id      BIGINT       NOT NULL,
    token_hash       VARCHAR(64)  NOT NULL,
    user_agent       VARCHAR(500),
    expires_at       TIMESTAMPTZ  NOT NULL,
    revoked_at       TIMESTAMPTZ,
    last_accessed_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(64),
    CONSTRAINT ck_mall_customer_session_expiry CHECK (expires_at > created_at)
);

CREATE UNIQUE INDEX uk_mall_customer_session_token_active
    ON mall_customer_session (token_hash) WHERE revoked_at IS NULL;
CREATE INDEX idx_mall_customer_session_account_active
    ON mall_customer_session (account_id, expires_at DESC) WHERE revoked_at IS NULL;

CREATE TABLE mall_customer_address
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT        NOT NULL,
    receiver_name  VARCHAR(100)  NOT NULL,
    phone          VARCHAR(32)   NOT NULL,
    region         VARCHAR(200)  NOT NULL,
    detail_address VARCHAR(300)  NOT NULL,
    is_default     BOOLEAN       NOT NULL DEFAULT FALSE,
    status         VARCHAR(16)   NOT NULL DEFAULT 'ENABLED',
    version        INTEGER       NOT NULL DEFAULT 0,
    deleted        BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(64),
    updated_by     VARCHAR(64),
    CONSTRAINT ck_mall_customer_address_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_mall_customer_address_version CHECK (version >= 0)
);

CREATE INDEX idx_mall_customer_address_customer_active
    ON mall_customer_address (customer_id, id) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_mall_customer_address_default_active
    ON mall_customer_address (customer_id) WHERE deleted = FALSE AND is_default = TRUE;

CREATE TABLE mall_cart_item
(
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT         NOT NULL,
    sku_id      BIGINT         NOT NULL,
    quantity    NUMERIC(18, 4) NOT NULL,
    version     INTEGER        NOT NULL DEFAULT 0,
    deleted     BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64),
    CONSTRAINT ck_mall_cart_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_mall_cart_item_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_mall_cart_item_customer_sku_active
    ON mall_cart_item (customer_id, sku_id) WHERE deleted = FALSE;
CREATE INDEX idx_mall_cart_item_customer_active
    ON mall_cart_item (customer_id, updated_at DESC) WHERE deleted = FALSE;
