CREATE TABLE customer_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code VARCHAR(64) NOT NULL,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_type_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_customer_type_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_customer_type_code_active
    ON customer_type (type_code) WHERE deleted = FALSE;

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(64) NOT NULL,
    name VARCHAR(150) NOT NULL,
    customer_type_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    visibility_policy VARCHAR(20) NOT NULL DEFAULT 'ALL_ENABLED',
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_customer_visibility_policy CHECK (visibility_policy IN ('ALL_ENABLED', 'ALLOWLIST')),
    CONSTRAINT ck_customer_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_customer_code_active
    ON customer (customer_code) WHERE deleted = FALSE;
CREATE INDEX idx_customer_type_id ON customer (customer_type_id);
CREATE INDEX idx_customer_name ON customer (name);

CREATE TABLE customer_sku_visibility (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_sku_visibility_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_customer_sku_visibility_active
    ON customer_sku_visibility (customer_id, sku_id) WHERE deleted = FALSE;
CREATE INDEX idx_customer_sku_visibility_sku_id
    ON customer_sku_visibility (sku_id);

CREATE TABLE customer_agreement_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    unit_price NUMERIC(18,4) NOT NULL,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    CONSTRAINT ck_customer_agreement_price_amount CHECK (unit_price >= 0),
    CONSTRAINT ck_customer_agreement_price_period CHECK (
        effective_to IS NULL OR effective_to > effective_from
    ),
    CONSTRAINT ck_customer_agreement_price_version CHECK (version >= 0)
);

CREATE INDEX idx_customer_agreement_price_lookup
    ON customer_agreement_price (customer_id, sku_id, effective_from, effective_to)
    WHERE deleted = FALSE;
