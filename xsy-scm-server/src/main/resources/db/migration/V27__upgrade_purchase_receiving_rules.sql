    ADD COLUMN reason VARCHAR(500);
ALTER TABLE purchase_receipt ADD CONSTRAINT ck_purchase_receipt_mode CHECK (receipt_mode IS NULL OR receipt_mode IN ('DIRECT', 'DEFERRED'));
ALTER TABLE purchase_receipt ADD CONSTRAINT ck_purchase_receipt_putaway_status CHECK (putaway_status IN ('NOT_APPLICABLE', 'PENDING_PUTAWAY', 'PUTAWAY_COMPLETED'));
CREATE INDEX idx_purchase_receipt_order_created ON purchase_receipt (purchase_order_id, created_at DESC) WHERE deleted = FALSE;

