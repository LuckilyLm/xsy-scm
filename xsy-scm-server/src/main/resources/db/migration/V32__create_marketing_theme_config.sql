-- 商城 Web / 小程序共用主题配置，始终读取 id 最小的一条当前配置。
CREATE TABLE marketing_theme_config
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theme_code         VARCHAR(32) NOT NULL,
    primary_color      VARCHAR(7)  NOT NULL,
    accent_color       VARCHAR(7)  NOT NULL,
    page_background    VARCHAR(7)  NOT NULL,
    card_radius        INTEGER    NOT NULL DEFAULT 16,
    card_style         VARCHAR(16) NOT NULL DEFAULT 'SHADOW',
    product_card_style VARCHAR(16) NOT NULL DEFAULT 'COMFORTABLE',
    navigation_style   VARCHAR(16) NOT NULL DEFAULT 'BOTTOM',
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by         VARCHAR(64),
    updated_by         VARCHAR(64),
    CONSTRAINT ck_marketing_theme_primary_color CHECK (primary_color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_marketing_theme_accent_color CHECK (accent_color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_marketing_theme_page_background CHECK (page_background ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_marketing_theme_card_radius CHECK (card_radius BETWEEN 0 AND 32),
    CONSTRAINT ck_marketing_theme_card_style CHECK (card_style IN ('FLAT', 'BORDER', 'SHADOW')),
    CONSTRAINT ck_marketing_theme_product_card_style CHECK (product_card_style IN ('COMPACT', 'COMFORTABLE', 'SPACIOUS')),
    CONSTRAINT ck_marketing_theme_navigation_style CHECK (navigation_style IN ('TOP', 'BOTTOM', 'SIDEBAR'))
);

CREATE UNIQUE INDEX uk_marketing_theme_config_singleton ON marketing_theme_config ((1));


