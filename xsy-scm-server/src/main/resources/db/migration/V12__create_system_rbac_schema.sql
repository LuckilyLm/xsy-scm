CREATE TABLE sys_department
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id      BIGINT,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(100) NOT NULL,
    leader_user_id BIGINT,
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    status         VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    version        INTEGER      NOT NULL DEFAULT 0,
    deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(64),
    updated_by     VARCHAR(64),
    CONSTRAINT ck_sys_department_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT ck_sys_department_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_sys_department_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_sys_department_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_sys_department_code_active
    ON sys_department (code) WHERE deleted = FALSE;
CREATE INDEX idx_sys_department_parent_active
    ON sys_department (parent_id, sort_order, id) WHERE deleted = FALSE;

