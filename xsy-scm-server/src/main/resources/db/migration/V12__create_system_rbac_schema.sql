CREATE UNIQUE INDEX uk_sys_user_email_active
    ON sys_user (LOWER(email)) WHERE deleted = FALSE AND email IS NOT NULL;
CREATE UNIQUE INDEX uk_sys_user_phone_active
    ON sys_user (phone) WHERE deleted = FALSE AND phone IS NOT NULL;
CREATE INDEX idx_sys_user_department_active
    ON sys_user (department_id, id) WHERE deleted = FALSE;

CREATE TABLE sys_role
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(100) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    status      VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    system_role BOOLEAN      NOT NULL DEFAULT FALSE,
    version     INTEGER      NOT NULL DEFAULT 0,
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64),
    CONSTRAINT ck_sys_role_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_sys_role_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_sys_role_code_active
    ON sys_role (code) WHERE deleted = FALSE;

CREATE TABLE sys_permission
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(160) NOT NULL,
    name              VARCHAR(100) NOT NULL,
    module            VARCHAR(64)  NOT NULL,
    resource_type     VARCHAR(16)  NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    system_permission BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order        INTEGER      NOT NULL DEFAULT 0,
    description       VARCHAR(500),
    version           INTEGER      NOT NULL DEFAULT 0,
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by        VARCHAR(64),
    updated_by        VARCHAR(64),
    CONSTRAINT ck_sys_permission_resource_type CHECK (resource_type IN ('PAGE', 'ACTION', 'API')),
    CONSTRAINT ck_sys_permission_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_sys_permission_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_sys_permission_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_sys_permission_code_active
    ON sys_permission (code) WHERE deleted = FALSE;
CREATE INDEX idx_sys_permission_module_active
    ON sys_permission (module, sort_order, id) WHERE deleted = FALSE;

CREATE TABLE sys_menu
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id                BIGINT,
    type                     VARCHAR(16)  NOT NULL,
    name                     VARCHAR(100) NOT NULL,
    path                     VARCHAR(255),
    route_key                VARCHAR(100),
    icon_key                 VARCHAR(64),
    required_permission_code VARCHAR(160),
    sort_order               INTEGER      NOT NULL DEFAULT 0,
    visible                  BOOLEAN      NOT NULL DEFAULT TRUE,
    status                   VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    version                  INTEGER      NOT NULL DEFAULT 0,
    deleted                  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by               VARCHAR(64),
    updated_by               VARCHAR(64),
    CONSTRAINT ck_sys_menu_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT ck_sys_menu_type CHECK (type IN ('DIRECTORY', 'PAGE')),
    CONSTRAINT ck_sys_menu_page_fields CHECK (
        (type = 'PAGE' AND path IS NOT NULL AND route_key IS NOT NULL)
            OR type = 'DIRECTORY'
        ),
    CONSTRAINT ck_sys_menu_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_sys_menu_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_sys_menu_version CHECK (version >= 0)
);

CREATE INDEX idx_sys_menu_parent_active
    ON sys_menu (parent_id, sort_order, id) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_sys_menu_route_key_active
    ON sys_menu (route_key) WHERE deleted = FALSE AND route_key IS NOT NULL;

