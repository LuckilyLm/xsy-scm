-- 鲜蔬源：preference模块最终结构与默认数据（截至原V244）。
-- 仅用于空库初始化；已有库先通过显式基线切换工具核对并接管。
CREATE SCHEMA IF NOT EXISTS xsy_v2;
SET search_path TO xsy_v2, public;
SET check_function_bodies = false;

CREATE TABLE xsy_v2.xsy_user_filter_preset (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy_v2.xsy_user_filter_preset_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  owner_key varchar(80) NOT NULL,
  view_key varchar(32) NOT NULL,
  name varchar(50) NOT NULL,
  conditions jsonb NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT xsy_user_filter_preset_conditions_check CHECK (jsonb_typeof(conditions) = CAST('array' AS text)
                                                        AND (jsonb_array_length(conditions) >= 1
                                                         AND jsonb_array_length(conditions) <= 8)),
  CONSTRAINT xsy_user_filter_preset_name_check CHECK (length(btrim(CAST(name AS text))) >= 1
                                                  AND length(btrim(CAST(name AS text))) <= 50),
  CONSTRAINT xsy_user_filter_preset_view_key_check CHECK (((view_key)::text = ANY ((ARRAY['PRODUCT'::character varying, 'SALES_ORDER'::character varying, 'PURCHASE_PRODUCT'::character varying])::text[]))),
  CONSTRAINT uk_user_filter_preset_name UNIQUE (owner_key, view_key, name),
  CONSTRAINT xsy_user_filter_preset_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE xsy_v2.xsy_user_filter_preset
  IS '用户筛选预设：员工保存的列表筛选条件。';

COMMENT ON COLUMN xsy_v2.xsy_user_filter_preset.id
  IS '主键 ID';

COMMENT ON COLUMN xsy_v2.xsy_user_filter_preset.owner_key
  IS '所属用户键';

COMMENT ON COLUMN xsy_v2.xsy_user_filter_preset.view_key
  IS '列表视图键';

COMMENT ON COLUMN xsy_v2.xsy_user_filter_preset.name
  IS '名称';

COMMENT ON COLUMN xsy_v2.xsy_user_filter_preset.conditions
  IS '筛选条件（JSON）';

COMMENT ON COLUMN xsy_v2.xsy_user_filter_preset.created_at
  IS '创建时间';

CREATE INDEX idx_user_filter_preset_owner_view
  ON xsy_v2.xsy_user_filter_preset (owner_key,
                                    view_key,
                                    id DESC);

SELECT pg_catalog.setval('xsy_v2.xsy_user_filter_preset_id_seq', 1, FALSE);

SET check_function_bodies = true;
