CREATE FUNCTION xsy.reject_order_discount_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.sales_order_id IS DISTINCT FROM OLD.sales_order_id
        OR NEW.discount_amount IS DISTINCT FROM OLD.discount_amount
        OR NEW.special_discount_amount IS DISTINCT FROM OLD.special_discount_amount
        OR NEW.allocations IS DISTINCT FROM OLD.allocations
        OR NEW.activity_snapshot IS DISTINCT FROM OLD.activity_snapshot
        OR NEW.coupon_snapshot IS DISTINCT FROM OLD.coupon_snapshot THEN
        RAISE EXCEPTION 'order_discount is an immutable snapshot';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION xsy.reject_order_promotion_gift_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.sales_order_id IS DISTINCT FROM OLD.sales_order_id
        OR NEW.activity_id IS DISTINCT FROM OLD.activity_id
        OR NEW.activity_version IS DISTINCT FROM OLD.activity_version
        OR NEW.sku_id IS DISTINCT FROM OLD.sku_id
        OR NEW.quantity IS DISTINCT FROM OLD.quantity
        OR NEW.rule_snapshot IS DISTINCT FROM OLD.rule_snapshot THEN
        RAISE EXCEPTION 'order_promotion_gift is a frozen entitlement';
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION xsy.xsy_reject_order_bundle_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'order bundle snapshot is immutable' USING ERRCODE = '23514';
END;
$$;

