  credit_period_value integer,
  credit_period_unit varchar(10),
  settle_day smallint,
  remark varchar(500),
  version integer DEFAULT 0 CONSTRAINT customer_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT customer_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT customer_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT customer_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  visibility_policy varchar(20) DEFAULT CAST('ALL_ENABLED' AS varchar) CONSTRAINT customer_visibility_policy_not_null NOT NULL,
  province_code integer,
  province_name varchar(32),
  city_code integer,
  city_name varchar(64),
  district_code integer,
  district_name varchar(64),
  longitude numeric(11, 8),
  latitude numeric(10, 8),
  geom_crs varchar(8),
  settlement_customer_id bigint CONSTRAINT customer_settlement_customer_id_not_null NOT NULL,
  cod_allowed boolean DEFAULT FALSE NOT NULL,
  mall_delivery_warehouse_id bigint,
  shared_settlement_enabled boolean DEFAULT FALSE NOT NULL,
  business_category_id bigint,
  customer_group_id bigint,
  CONSTRAINT ck_customer_coordinate_pair CHECK ((longitude IS NULL) = (latitude IS NULL)),
  CONSTRAINT ck_customer_credit_limit CHECK (credit_limit >= CAST(0 AS numeric)),
  CONSTRAINT ck_customer_credit_period CHECK ((((credit_period_type IS NULL) AND (credit_amount_threshold IS NULL) AND (credit_period_value IS NULL) AND (credit_period_unit IS NULL) AND (settle_day IS NULL)) OR (((credit_period_type)::text = 'BY_AMOUNT'::text) AND (credit_amount_threshold IS NOT NULL) AND (credit_amount_threshold >= (0)::numeric) AND (credit_period_value IS NULL) AND (credit_period_unit IS NULL) AND (settle_day IS NULL)) OR (((credit_period_type)::text = 'BY_TIME'::text) AND (credit_amount_threshold IS NULL) AND (credit_period_value IS NOT NULL) AND (credit_period_value > 0) AND ((credit_period_unit)::text = ANY ((ARRAY['DAY'::character varying, 'MONTH'::character varying])::text[])) AND ((((credit_period_unit)::text = 'DAY'::text) AND (settle_day IS NULL)) OR (((credit_period_unit)::text = 'MONTH'::text) AND ((settle_day IS NULL) OR ((settle_day >= 1) AND (settle_day <= 28)))))))),
  CONSTRAINT ck_customer_crs_with_coordinate CHECK (geom_crs IS NULL
                                                 OR (longitude IS NOT NULL
                                                 AND latitude IS NOT NULL)),
  CONSTRAINT ck_customer_geom_crs CHECK (((geom_crs IS NULL) OR ((geom_crs)::text = ANY ((ARRAY['GCJ02'::character varying, 'WGS84'::character varying])::text[])))),
  CONSTRAINT ck_customer_latitude CHECK (latitude IS NULL
                                      OR (latitude >= CAST(CAST('-90' AS integer) AS numeric)
                                      AND latitude <= CAST(90 AS numeric))),
  CONSTRAINT ck_customer_location_complete CHECK ((((longitude IS NULL) AND (latitude IS NULL) AND (geom_crs IS NULL)) OR ((longitude IS NOT NULL) AND (latitude IS NOT NULL) AND (geom_crs IS NOT NULL) AND ((longitude >= ('-180'::integer)::numeric) AND (longitude <= (180)::numeric)) AND ((latitude >= ('-90'::integer)::numeric) AND (latitude <= (90)::numeric)) AND ((geom_crs)::text = ANY ((ARRAY['GCJ02'::character varying, 'WGS84'::character varying])::text[]))))),
  CONSTRAINT ck_customer_longitude CHECK (longitude IS NULL
                                       OR (longitude >= CAST(CAST('-180' AS integer) AS numeric)
                                       AND longitude <= CAST(180 AS numeric))),
  CONSTRAINT ck_customer_self_parent CHECK (parent_customer_id IS NULL
                                         OR parent_customer_id <> id),
  CONSTRAINT ck_customer_settle_mode CHECK (((settle_mode)::text = ANY ((ARRAY['INDEPENDENT'::character varying, 'GROUP'::character varying])::text[]))),
  CONSTRAINT ck_customer_settlement_not_self_parent CHECK (settlement_customer_id > 0),
  CONSTRAINT ck_customer_shared_settlement_scope CHECK (NOT shared_settlement_enabled
                                                     OR CAST(settle_mode AS text) = CAST('GROUP' AS text)),
  CONSTRAINT ck_customer_status CHECK (((status)::text = ANY ((ARRAY['COOPERATING'::character varying, 'SUSPENDED'::character varying, 'BLACKLIST'::character varying])::text[]))),
  CONSTRAINT ck_customer_version CHECK (version >= 0),
  CONSTRAINT ck_customer_visibility_policy CHECK (((visibility_policy)::text = ANY ((ARRAY['ALL_ENABLED'::character varying, 'ALLOWLIST'::character varying])::text[]))),
  CONSTRAINT customer_pkey PRIMARY KEY (id)
);

