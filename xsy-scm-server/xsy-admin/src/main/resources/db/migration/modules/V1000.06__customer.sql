CREATE FUNCTION xsy_v2.default_customer_settlement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.settlement_customer_id = COALESCE(NEW.settlement_customer_id, NEW.id);
    RETURN NEW;
END $$;

CREATE TABLE xsy_v2.xsy_customer (
  id bigint CONSTRAINT customer_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy_v2.customer_id_seq
                                                                                       START WITH 1
                                                                                       INCREMENT BY 1
                                                                                       NO MINVALUE
                                                                                       NO MAXVALUE
                                                                                       CACHE 1),
  customer_code varchar(64) CONSTRAINT customer_customer_code_not_null NOT NULL,
  name varchar(150) CONSTRAINT customer_name_not_null NOT NULL,
  status varchar(20) DEFAULT CAST('COOPERATING' AS varchar) CONSTRAINT customer_status_not_null NOT NULL,
