CREATE SCHEMA IF NOT EXISTS xsy_v2;
SET search_path TO xsy_v2, public;
SET check_function_bodies = false;

CREATE TABLE xsy_v2.xsy_business_category (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy_v2.xsy_business_category_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  scope varchar(16) NOT NULL,
  category_code varchar(64) NOT NULL,
  name varchar(64) NOT NULL,
  parent_id bigint,
  level smallint DEFAULT 1 NOT NULL,
  status varchar(16) DEFAULT CAST('ENABLED' AS varchar) NOT NULL,
  sort_order integer DEFAULT 0 NOT NULL,
  version integer DEFAULT 0 NOT NULL,
  deleted boolean DEFAULT FALSE NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  updated_at timestamp with time zone DEFAULT now() NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  CONSTRAINT ck_business_category_level CHECK (level >= 1
                                           AND level <= 3),
  CONSTRAINT ck_business_category_scope CHECK (((scope)::text = ANY ((ARRAY['CUSTOMER'::character varying, 'SUPPLIER'::character varying])::text[]))),
  CONSTRAINT ck_business_category_self_parent CHECK (parent_id IS NULL
                                                  OR parent_id <> id),
  CONSTRAINT ck_business_category_status CHECK (((status)::text = ANY ((ARRAY['ENABLED'::character varying, 'DISABLED'::character varying])::text[]))),
  CONSTRAINT ck_business_category_version CHECK (version >= 0),
  CONSTRAINT xsy_business_category_pkey PRIMARY KEY (id)
);

