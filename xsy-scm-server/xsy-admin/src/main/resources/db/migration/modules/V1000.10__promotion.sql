CREATE TABLE xsy.xsy_promotion_coupon (
  id bigint CONSTRAINT promotion_coupon_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.promotion_coupon_id_seq
