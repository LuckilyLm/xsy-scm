CREATE TABLE xsy.xsy_promotion_activity (
  id bigint CONSTRAINT promotion_activity_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.promotion_activity_id_seq
                                                                                                 START WITH 1
                                                                                                 INCREMENT BY 1
                                                                                                 NO MINVALUE
                                                                                                 NO MAXVALUE
                                                                                                 CACHE 1),
  activity_code varchar(64) CONSTRAINT promotion_activity_activity_code_not_null NOT NULL,
  activity_name varchar(150) CONSTRAINT promotion_activity_activity_name_not_null NOT NULL,
  activity_type varchar(24) CONSTRAINT promotion_activity_activity_type_not_null NOT NULL,
  exclusive_group varchar(64),
  priority integer DEFAULT 0 CONSTRAINT promotion_activity_priority_not_null NOT NULL,
  valid_from timestamp with time zone CONSTRAINT promotion_activity_valid_from_not_null NOT NULL,
  valid_to timestamp with time zone CONSTRAINT promotion_activity_valid_to_not_null NOT NULL,
  status varchar(16) DEFAULT CAST('DRAFT' AS varchar) CONSTRAINT promotion_activity_status_not_null NOT NULL,
  rule jsonb CONSTRAINT promotion_activity_rule_not_null NOT NULL,
  remark varchar(200),
  version integer DEFAULT 0 CONSTRAINT promotion_activity_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT promotion_activity_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT promotion_activity_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT promotion_activity_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  CONSTRAINT ck_promotion_activity_rule CHECK (jsonb_typeof(rule) = CAST('object' AS text)),
  CONSTRAINT ck_promotion_activity_status CHECK (((status)::text = ANY ((ARRAY['DRAFT'::character varying, 'ACTIVE'::character varying, 'STOPPED'::character varying])::text[]))),
  CONSTRAINT ck_promotion_activity_type CHECK (((activity_type)::text = ANY ((ARRAY['FULL_REDUCE'::character varying, 'DISCOUNT'::character varying, 'FULL_GIFT'::character varying, 'SPECIAL_PRICE'::character varying])::text[]))),
  CONSTRAINT ck_promotion_activity_window CHECK (valid_from < valid_to),
  CONSTRAINT promotion_activity_pkey PRIMARY KEY (id)
