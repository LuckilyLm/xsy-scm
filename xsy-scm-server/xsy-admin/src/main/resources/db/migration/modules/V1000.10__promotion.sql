  discount_type varchar(16) CONSTRAINT promotion_coupon_discount_type_not_null NOT NULL,
  discount_value numeric(18, 4) CONSTRAINT promotion_coupon_discount_value_not_null NOT NULL,
  min_order_amount numeric(18, 4) DEFAULT 0 CONSTRAINT promotion_coupon_min_order_amount_not_null NOT NULL,
