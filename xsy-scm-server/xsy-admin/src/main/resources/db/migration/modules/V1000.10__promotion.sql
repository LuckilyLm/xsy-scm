CREATE TABLE xsy.xsy_promotion_coupon_instance (
  id bigint CONSTRAINT promotion_coupon_instance_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.promotion_coupon_instance_id_seq
                                                                                                        START WITH 1
                                                                                                        INCREMENT BY 1
                                                                                                        NO MINVALUE
                                                                                                        NO MAXVALUE
                                                                                                        CACHE 1),
  coupon_id bigint CONSTRAINT promotion_coupon_instance_coupon_id_not_null NOT NULL,
  customer_id bigint CONSTRAINT promotion_coupon_instance_customer_id_not_null NOT NULL,
  instance_no varchar(64) CONSTRAINT promotion_coupon_instance_instance_no_not_null NOT NULL,
  status varchar(16) DEFAULT CAST('AVAILABLE' AS varchar) CONSTRAINT promotion_coupon_instance_status_not_null NOT NULL,
  reserved_order_id bigint,
  reserved_at timestamp with time zone,
  used_order_id bigint,
  used_at timestamp with time zone,
  released_at timestamp with time zone,
  release_reason varchar(200),
  version integer DEFAULT 0 CONSTRAINT promotion_coupon_instance_version_not_null NOT NULL,
  issue_source varchar(16) DEFAULT CAST('ADMIN_ISSUE' AS varchar) NOT NULL,
  CONSTRAINT ck_promotion_coupon_instance_issue_source CHECK (((issue_source)::text = ANY ((ARRAY['ADMIN_ISSUE'::character varying, 'MALL_CLAIM'::character varying])::text[]))),
  CONSTRAINT ck_promotion_coupon_instance_released CHECK (CAST(status AS text) <> CAST('RELEASED' AS text)
                                                       OR released_at IS NOT NULL),
  CONSTRAINT ck_promotion_coupon_instance_reserved CHECK (CAST(status AS text) <> CAST('RESERVED' AS text)
                                                       OR (reserved_order_id IS NOT NULL
                                                       AND reserved_at IS NOT NULL)),
  CONSTRAINT ck_promotion_coupon_instance_status CHECK (((status)::text = ANY ((ARRAY['AVAILABLE'::character varying, 'RESERVED'::character varying, 'USED'::character varying, 'RELEASED'::character varying])::text[]))),
  CONSTRAINT ck_promotion_coupon_instance_used CHECK (CAST(status AS text) <> CAST('USED' AS text)
                                                   OR (used_order_id IS NOT NULL
                                                   AND used_at IS NOT NULL)),
  CONSTRAINT promotion_coupon_instance_pkey PRIMARY KEY (id),
  CONSTRAINT uk_promotion_coupon_instance UNIQUE (coupon_id, customer_id, instance_no)
);

