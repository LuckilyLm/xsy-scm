CREATE INDEX idx_supplier_business_category
  ON xsy.xsy_supplier (business_category_id)
  WHERE deleted = FALSE
    AND business_category_id IS NOT NULL;

CREATE INDEX idx_supplier_city_active
  ON xsy.xsy_supplier (city_code)
  WHERE deleted = FALSE
    AND city_code IS NOT NULL;

CREATE INDEX idx_supplier_name
  ON xsy.xsy_supplier (name);

CREATE INDEX idx_supplier_sku_purchaser
  ON xsy.xsy_supplier_sku (purchaser_id)
  WHERE deleted = FALSE
    AND purchaser_id IS NOT NULL;

CREATE INDEX idx_supplier_sku_sku_id
  ON xsy.xsy_supplier_sku (sku_id)
  WHERE deleted = FALSE;

CREATE INDEX idx_supplier_status
  ON xsy.xsy_supplier (status);

CREATE UNIQUE INDEX uk_supplier_code_active
  ON xsy.xsy_supplier (supplier_code)
  WHERE deleted = FALSE;

CREATE UNIQUE INDEX uk_supplier_sku_active
  ON xsy.xsy_supplier_sku (supplier_id,
                              sku_id)
  WHERE deleted = FALSE;

CREATE UNIQUE INDEX uk_supplier_sku_item_code_active
  ON xsy.xsy_supplier_sku (supplier_id,
                              supplier_item_code)
  WHERE deleted = FALSE
    AND supplier_item_code IS NOT NULL;

