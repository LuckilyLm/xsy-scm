CREATE TABLE xsy.xsy_supplier_sku (
  id bigint CONSTRAINT supplier_sku_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.supplier_sku_id_seq
                                                                                           START WITH 1
                                                                                           INCREMENT BY 1
                                                                                           NO MINVALUE
                                                                                           NO MAXVALUE
                                                                                           CACHE 1),
  supplier_id bigint CONSTRAINT supplier_sku_supplier_id_not_null NOT NULL,
  sku_id bigint CONSTRAINT supplier_sku_sku_id_not_null NOT NULL,
  supplier_code_snapshot varchar(64) CONSTRAINT supplier_sku_supplier_code_snapshot_not_null NOT NULL,
  supplier_name_snapshot varchar(150) CONSTRAINT supplier_sku_supplier_name_snapshot_not_null NOT NULL,
  sku_code_snapshot varchar(64) CONSTRAINT supplier_sku_sku_code_snapshot_not_null NOT NULL,
  sku_name_snapshot varchar(150) CONSTRAINT supplier_sku_sku_name_snapshot_not_null NOT NULL,
  spec_values_snapshot jsonb DEFAULT CAST('{}' AS jsonb) CONSTRAINT supplier_sku_spec_values_snapshot_not_null NOT NULL,
  purchase_unit varchar(32) CONSTRAINT supplier_sku_purchase_unit_not_null NOT NULL,
  reference_price numeric(18, 4),
  purchaser_id bigint,
  is_default boolean DEFAULT FALSE CONSTRAINT supplier_sku_is_default_not_null NOT NULL,
  status varchar(16) DEFAULT CAST('ENABLED' AS varchar) CONSTRAINT supplier_sku_status_not_null NOT NULL,
  version integer DEFAULT 0 CONSTRAINT supplier_sku_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT supplier_sku_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT supplier_sku_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT supplier_sku_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  supplier_item_code varchar(100),
  CONSTRAINT ck_supplier_sku_item_code_nonblank CHECK (supplier_item_code IS NULL
                                                    OR length(btrim(CAST(supplier_item_code AS text))) > 0),
  CONSTRAINT ck_supplier_sku_reference_price CHECK (reference_price IS NULL
                                                 OR reference_price >= CAST(0 AS numeric)),
  CONSTRAINT ck_supplier_sku_spec_values CHECK (jsonb_typeof(spec_values_snapshot) = CAST('object' AS text)),
  CONSTRAINT ck_supplier_sku_status CHECK (((status)::text = ANY ((ARRAY['ENABLED'::character varying, 'DISABLED'::character varying])::text[]))),
  CONSTRAINT ck_supplier_sku_version CHECK (version >= 0),
  CONSTRAINT supplier_sku_pkey PRIMARY KEY (id)
);

