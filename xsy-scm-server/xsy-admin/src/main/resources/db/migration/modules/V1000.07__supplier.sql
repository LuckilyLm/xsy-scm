-- 鲜蔬源：supplier模块最终结构与默认数据（截至原V244）。
-- 仅用于空库初始化；已有库先通过显式基线切换工具核对并接管。
CREATE SCHEMA IF NOT EXISTS xsy;
SET search_path TO xsy, public;
SET check_function_bodies = false;

CREATE SEQUENCE xsy.supplier_code_seq
  START WITH 1
  INCREMENT BY 1
  NO MINVALUE
  NO MAXVALUE
  CACHE 1;

CREATE TABLE xsy.xsy_supplier (
  id bigint CONSTRAINT supplier_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.supplier_id_seq
                                                                                       START WITH 1
                                                                                       INCREMENT BY 1
                                                                                       NO MINVALUE
                                                                                       NO MAXVALUE
                                                                                       CACHE 1),
  supplier_code varchar(64) CONSTRAINT supplier_supplier_code_not_null NOT NULL,
  name varchar(150) CONSTRAINT supplier_name_not_null NOT NULL,
  status varchar(16) DEFAULT CAST('ENABLED' AS varchar) CONSTRAINT supplier_status_not_null NOT NULL,
  contact_name varchar(100),
  contact_phone varchar(32),
  address varchar(255),
  remark varchar(500),
  version integer DEFAULT 0 CONSTRAINT supplier_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT supplier_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT supplier_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT supplier_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  province_code integer,
  province_name varchar(32),
  city_code integer,
  city_name varchar(64),
  district_code integer,
  district_name varchar(64),
  longitude numeric(11, 8),
  latitude numeric(10, 8),
  geom_crs varchar(8),
  payment_period_days integer DEFAULT 0 CONSTRAINT supplier_payment_period_days_not_null NOT NULL,
  business_category_id bigint,
  CONSTRAINT ck_supplier_coordinate_pair CHECK ((longitude IS NULL) = (latitude IS NULL)),
  CONSTRAINT ck_supplier_crs_with_coordinate CHECK (geom_crs IS NULL
                                                 OR (longitude IS NOT NULL
                                                 AND latitude IS NOT NULL)),
  CONSTRAINT ck_supplier_geom_crs CHECK (((geom_crs IS NULL) OR ((geom_crs)::text = ANY ((ARRAY['GCJ02'::character varying, 'WGS84'::character varying])::text[])))),
  CONSTRAINT ck_supplier_latitude CHECK (latitude IS NULL
                                      OR (latitude >= CAST(CAST('-90' AS integer) AS numeric)
                                      AND latitude <= CAST(90 AS numeric))),
  CONSTRAINT ck_supplier_longitude CHECK (longitude IS NULL
                                       OR (longitude >= CAST(CAST('-180' AS integer) AS numeric)
                                       AND longitude <= CAST(180 AS numeric))),
  CONSTRAINT ck_supplier_payment_period_days CHECK (payment_period_days >= 0
                                                AND payment_period_days <= 3650),
  CONSTRAINT ck_supplier_status CHECK (((status)::text = ANY ((ARRAY['ENABLED'::character varying, 'DISABLED'::character varying])::text[]))),
  CONSTRAINT ck_supplier_version CHECK (version >= 0),
  CONSTRAINT supplier_pkey PRIMARY KEY (id)
);

