CREATE TABLE xsy.xsy_customer_agreement_price (
  id bigint CONSTRAINT customer_agreement_price_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.customer_agreement_price_id_seq
                                                                                                       START WITH 1
                                                                                                       INCREMENT BY 1
                                                                                                       NO MINVALUE
                                                                                                       NO MAXVALUE
                                                                                                       CACHE 1),
  customer_id bigint CONSTRAINT customer_agreement_price_customer_id_not_null NOT NULL,
  sku_id bigint CONSTRAINT customer_agreement_price_sku_id_not_null NOT NULL,
  unit_price numeric(18, 4),
  effective_from timestamp with time zone CONSTRAINT customer_agreement_price_effective_from_not_null NOT NULL,
  effective_to timestamp with time zone,
  version integer DEFAULT 0 CONSTRAINT customer_agreement_price_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT customer_agreement_price_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT customer_agreement_price_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT customer_agreement_price_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  formula_type varchar(32) DEFAULT CAST('FIXED' AS varchar) NOT NULL,
  formula_parameter numeric(18, 4),
  CONSTRAINT ck_agreement_price_formula CHECK (((((formula_type)::text = 'FIXED'::text) AND (unit_price IS NOT NULL) AND (formula_parameter IS NULL)) OR (((formula_type)::text = ANY ((ARRAY['MARKET_PLUS_AMOUNT'::character varying, 'COST_MARKUP_RATE'::character varying, 'MARKET_MARKUP_RATE'::character varying, 'PURCHASE_COST_LOSS_TAX_MARKUP'::character varying])::text[])) AND (unit_price IS NULL) AND (formula_parameter IS NOT NULL) AND (formula_parameter >= (0)::numeric)))),
  CONSTRAINT ck_customer_agreement_price_amount CHECK (unit_price >= CAST(0 AS numeric)),
  CONSTRAINT ck_customer_agreement_price_period CHECK (effective_to IS NULL
                                                    OR effective_to > effective_from),
  CONSTRAINT ck_customer_agreement_price_version CHECK (version >= 0),
  CONSTRAINT customer_agreement_price_pkey PRIMARY KEY (id)
);

