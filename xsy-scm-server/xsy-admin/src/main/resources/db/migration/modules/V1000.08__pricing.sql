CREATE TABLE xsy.xsy_price_operation_log (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.xsy_price_operation_log_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  price_type varchar(20) NOT NULL,
  price_id bigint NOT NULL,
  operation_type varchar(20) NOT NULL,
  operator varchar(64) NOT NULL,
  before_data jsonb,
  after_data jsonb,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  created_by varchar(64),
  CONSTRAINT ck_price_operation_log_after CHECK (after_data IS NULL
                                              OR jsonb_typeof(after_data) = CAST('object' AS text)),
  CONSTRAINT ck_price_operation_log_before CHECK (before_data IS NULL
                                               OR jsonb_typeof(before_data) = CAST('object' AS text)),
  CONSTRAINT ck_price_operation_log_operation CHECK (((operation_type)::text = ANY ((ARRAY['CREATE'::character varying, 'UPDATE'::character varying, 'DELETE'::character varying])::text[]))),
  CONSTRAINT ck_price_operation_log_type CHECK (((price_type)::text = ANY ((ARRAY['AGREEMENT'::character varying, 'CUSTOMER_TYPE'::character varying, 'CUSTOMER_GROUP'::character varying, 'TIME_PRICE'::character varying])::text[]))),
  CONSTRAINT xsy_price_operation_log_pkey PRIMARY KEY (id)
);

