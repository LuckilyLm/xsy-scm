CREATE TABLE xsy.xsy_scale_job_lease (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.xsy_scale_job_lease_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  device_id bigint NOT NULL,
  session_id bigint NOT NULL,
  employee_id bigint NOT NULL,
  task_id bigint NOT NULL,
  task_version integer NOT NULL,
  leased_at timestamp with time zone DEFAULT now() NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  released_at timestamp with time zone,
  release_reason varchar(200),
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT ck_scale_job_lease_expiry CHECK (expires_at > leased_at),
  CONSTRAINT ck_scale_job_lease_release CHECK (released_at IS NULL
                                            OR released_at >= leased_at),
  CONSTRAINT xsy_scale_job_lease_task_version_check CHECK (task_version >= 0),
  CONSTRAINT xsy_scale_job_lease_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE xsy.xsy_scale_job_lease
  IS '秤端领取分拣任务的工作租约；同一任务同时只能有一个有效租约';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.id
  IS '主键 ID';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.device_id
  IS '设备 ID';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.session_id
  IS '关联 xsy_scale_device_session.id；租约失效后不能继续写业务';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.employee_id
  IS '员工 ID';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.task_id
  IS '任务 ID';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.task_version
  IS '领取时的任务版本；改派或重开后版本变化，旧租约必须重新领取';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.leased_at
  IS '租约开始时间';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.expires_at
  IS '过期时间';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.released_at
  IS '释放时间；为空表示租约仍有效，部分唯一索引据此仲裁并发领取';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.release_reason
  IS '租约释放原因';

COMMENT ON COLUMN xsy.xsy_scale_job_lease.created_at
  IS '创建时间';

