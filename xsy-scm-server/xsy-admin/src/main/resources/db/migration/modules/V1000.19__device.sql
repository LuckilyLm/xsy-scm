CREATE TABLE xsy.xsy_scale_device_session (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.xsy_scale_device_session_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  device_id bigint NOT NULL,
  employee_id bigint NOT NULL,
  session_token_hash varchar(128) NOT NULL,
  issued_at timestamp with time zone DEFAULT now() NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  ended_at timestamp with time zone,
  end_reason varchar(200),
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  created_by varchar(64),
  CONSTRAINT ck_scale_device_session_end CHECK (ended_at IS NULL
                                             OR ended_at >= issued_at),
  CONSTRAINT ck_scale_device_session_expiry CHECK (expires_at > issued_at),
  CONSTRAINT xsy_scale_device_session_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE xsy.xsy_scale_device_session
  IS '设备上的员工授权会话；把「哪台秤」与「谁在操作」分开记录，业务写入记真实员工';

COMMENT ON COLUMN xsy.xsy_scale_device_session.id
  IS '主键 ID';

COMMENT ON COLUMN xsy.xsy_scale_device_session.device_id
  IS '关联 xsy_scale_device.id；不建外键，由领域服务校验';

COMMENT ON COLUMN xsy.xsy_scale_device_session.employee_id
  IS '关联 t_employee.id；业务写入的 accepted_by / sorted_by 取该员工';

COMMENT ON COLUMN xsy.xsy_scale_device_session.session_token_hash
  IS '秤端 X-Operator-Session 的令牌摘要；不接受客户端自报员工 ID';

COMMENT ON COLUMN xsy.xsy_scale_device_session.issued_at
  IS '会话签发时间';

COMMENT ON COLUMN xsy.xsy_scale_device_session.expires_at
  IS '过期时间';

COMMENT ON COLUMN xsy.xsy_scale_device_session.ended_at
  IS '会话结束时间；结束原因写入 end_reason，不删除历史';

COMMENT ON COLUMN xsy.xsy_scale_device_session.end_reason
  IS '会话结束原因';

COMMENT ON COLUMN xsy.xsy_scale_device_session.created_at
  IS '创建时间';

COMMENT ON COLUMN xsy.xsy_scale_device_session.created_by
  IS '创建人（用户类型:用户 ID）';

CREATE TABLE xsy.xsy_scale_item_completion (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.xsy_scale_item_completion_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  operation_id varchar(160) NOT NULL,
  task_id bigint NOT NULL,
  task_item_id bigint NOT NULL,
  device_id bigint NOT NULL,
  device_session_id bigint NOT NULL,
  employee_id bigint NOT NULL,
  basket_count integer NOT NULL,
  total_quantity numeric(18, 4) NOT NULL,
  business_unit varchar(32) NOT NULL,
  manifest_hash varchar(64) NOT NULL,
  result varchar(16) NOT NULL,
  reason varchar(500),
  quantity_before numeric(18, 4),
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  created_by varchar(64) NOT NULL,
  CONSTRAINT ck_scale_item_completion_count CHECK (basket_count > 0),
  CONSTRAINT ck_scale_item_completion_result CHECK (((result)::text = ANY ((ARRAY['NORMAL'::character varying, 'SHORT'::character varying, 'OUT_OF_STOCK'::character varying, 'OVER'::character varying])::text[]))),
  CONSTRAINT ck_scale_item_completion_total CHECK (total_quantity >= CAST(0 AS numeric)),
  CONSTRAINT uk_scale_item_completion_operation UNIQUE (operation_id),
  CONSTRAINT xsy_scale_item_completion_pkey PRIMARY KEY (id)
);

