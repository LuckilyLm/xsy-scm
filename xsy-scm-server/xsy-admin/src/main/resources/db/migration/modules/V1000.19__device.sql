CREATE SCHEMA IF NOT EXISTS xsy;
SET search_path TO xsy, public;
SET check_function_bodies = false;

CREATE TABLE xsy.xsy_scale_device (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.xsy_scale_device_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  device_code varchar(64) NOT NULL,
  device_name varchar(100),
  device_model varchar(100),
  warehouse_id bigint NOT NULL,
  station_code varchar(64),
  status varchar(24) DEFAULT CAST('PENDING_ACTIVATION' AS varchar) NOT NULL,
  protocol_type varchar(40),
  agent_version varchar(40),
  pairing_code_hash varchar(128),
  pairing_expires_at timestamp with time zone,
  credential_hash varchar(128),
  credential_expires_at timestamp with time zone,
  last_seen_at timestamp with time zone,
  last_reading_at timestamp with time zone,
  queue_depth integer,
  scale_connected boolean,
  printer_connected boolean,
  revoked_at timestamp with time zone,
  revoked_by varchar(64),
  version integer DEFAULT 0 NOT NULL,
  deleted boolean DEFAULT FALSE NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  updated_at timestamp with time zone DEFAULT now() NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  CONSTRAINT xsy_scale_device_device_code_check CHECK (btrim(CAST(device_code AS text)) <> CAST('' AS text)),
  CONSTRAINT xsy_scale_device_queue_depth_check CHECK (queue_depth IS NULL
                                                    OR queue_depth >= 0),
  CONSTRAINT xsy_scale_device_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING_ACTIVATION'::character varying, 'ACTIVE'::character varying, 'SUSPENDED'::character varying, 'REVOKED'::character varying])::text[]))),
  CONSTRAINT xsy_scale_device_version_check CHECK (version >= 0),
  CONSTRAINT xsy_scale_device_pkey PRIMARY KEY (id)
);

