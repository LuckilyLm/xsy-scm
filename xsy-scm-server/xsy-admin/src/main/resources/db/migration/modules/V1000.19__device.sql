  ON xsy.xsy_scale_item_completion (task_item_id,
                                       id DESC);

CREATE INDEX idx_scale_job_lease_device
  ON xsy.xsy_scale_job_lease (device_id,
                                 expires_at DESC);

CREATE INDEX idx_scale_job_lease_employee
  ON xsy.xsy_scale_job_lease (employee_id,
                                 expires_at DESC);

CREATE UNIQUE INDEX uk_scale_device_code
  ON xsy.xsy_scale_device (device_code)
  WHERE deleted = FALSE;

CREATE UNIQUE INDEX uk_scale_device_credential
  ON xsy.xsy_scale_device (credential_hash)
  WHERE credential_hash IS NOT NULL;

