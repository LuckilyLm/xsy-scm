CREATE TABLE xsy.xsy_customer_balance_movement (
  id bigint CONSTRAINT customer_balance_movement_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.customer_balance_movement_id_seq
                                                                                                        START WITH 1
                                                                                                        INCREMENT BY 1
                                                                                                        NO MINVALUE
                                                                                                        NO MAXVALUE
                                                                                                        CACHE 1),
  movement_no varchar(64) CONSTRAINT customer_balance_movement_movement_no_not_null NOT NULL,
  account_id bigint CONSTRAINT customer_balance_movement_account_id_not_null NOT NULL,
  settlement_customer_id bigint CONSTRAINT customer_balance_movement_settlement_customer_id_not_null NOT NULL,
  customer_id bigint,
  type varchar(16) CONSTRAINT customer_balance_movement_type_not_null NOT NULL,
  direction varchar(8) CONSTRAINT customer_balance_movement_direction_not_null NOT NULL,
  amount numeric(18, 4) CONSTRAINT customer_balance_movement_amount_not_null NOT NULL,
  source_type varchar(32),
  source_id bigint,
  reason varchar(500),
  occurred_at timestamp with time zone CONSTRAINT customer_balance_movement_occurred_at_not_null NOT NULL,
  version integer DEFAULT 0 CONSTRAINT customer_balance_movement_version_not_null NOT NULL,
  deleted boolean DEFAULT FALSE CONSTRAINT customer_balance_movement_deleted_not_null NOT NULL,
  created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT customer_balance_movement_created_at_not_null NOT NULL,
  updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT customer_balance_movement_updated_at_not_null NOT NULL,
  created_by varchar(64),
  updated_by varchar(64),
  CONSTRAINT ck_customer_balance_movement_append_only CHECK (deleted = FALSE),
  CONSTRAINT ck_customer_balance_movement_business_source CHECK (((((type)::text = 'RECHARGE'::text) AND ((direction)::text = 'CREDIT'::text) AND ((source_type)::text = 'PAYMENT_TRANSACTION'::text) AND (source_id IS NOT NULL)) OR (((type)::text = 'CONSUME'::text) AND ((direction)::text = 'DEBIT'::text) AND ((source_type)::text = 'PAYMENT_INTENT'::text) AND (source_id IS NOT NULL)) OR (((type)::text = 'REFUND'::text) AND ((direction)::text = 'CREDIT'::text) AND ((source_type)::text = ANY ((ARRAY['ORDER_REFUND'::character varying, 'REFUND_FUNDING_ALLOCATION'::character varying])::text[])) AND (source_id IS NOT NULL)) OR (((type)::text = 'CORRECTION'::text) AND (source_type IS NULL) AND (source_id IS NULL) AND (btrim((COALESCE(reason, ''::character varying))::text) <> ''::text)))),
  CONSTRAINT ck_customer_balance_movement_correction_reason CHECK (CAST(type AS text) <> CAST('CORRECTION' AS text)
                                                                OR btrim(CAST(COALESCE(reason,
                                                                                       CAST('' AS varchar)) AS text)) <> CAST('' AS text)),
  CONSTRAINT ck_customer_balance_movement_direction CHECK (((direction)::text = ANY ((ARRAY['CREDIT'::character varying, 'DEBIT'::character varying])::text[]))),
  CONSTRAINT ck_customer_balance_movement_source_pairing CHECK ((source_type IS NULL
                                                             AND source_id IS NULL)
                                                             OR (source_type IS NOT NULL
                                                             AND source_id IS NOT NULL)),
  CONSTRAINT ck_customer_balance_movement_source_type CHECK (((source_type IS NULL) OR ((source_type)::text = ANY ((ARRAY['PAYMENT_TRANSACTION'::character varying, 'PAYMENT_INTENT'::character varying, 'ORDER_REFUND'::character varying, 'REFUND_FUNDING_ALLOCATION'::character varying])::text[])))),
  CONSTRAINT ck_customer_balance_movement_type CHECK (((type)::text = ANY ((ARRAY['RECHARGE'::character varying, 'CONSUME'::character varying, 'REFUND'::character varying, 'CORRECTION'::character varying])::text[]))),
  CONSTRAINT ck_customer_balance_movement_type_direction CHECK ((CAST(type AS text) = CAST('RECHARGE' AS text)
                                                             AND CAST(direction AS text) = CAST('CREDIT' AS text))
                                                             OR (CAST(type AS text) = CAST('CONSUME' AS text)
                                                             AND CAST(direction AS text) = CAST('DEBIT' AS text))
                                                             OR (CAST(type AS text) = CAST('REFUND' AS text)
                                                             AND CAST(direction AS text) = CAST('CREDIT' AS text))
                                                             OR CAST(type AS text) = CAST('CORRECTION' AS text)),
  CONSTRAINT customer_balance_movement_amount_check CHECK (amount > CAST(0 AS numeric)),
  CONSTRAINT customer_balance_movement_movement_no_check CHECK (btrim(CAST(movement_no AS text)) <> CAST('' AS text)),
  CONSTRAINT customer_balance_movement_version_check CHECK (version >= 0),
  CONSTRAINT customer_balance_movement_pkey PRIMARY KEY (id)
);

