CREATE TRIGGER trg_negative_stock_snapshot_append_only
  BEFORE DELETE OR UPDATE
  ON xsy.xsy_report_negative_stock_snapshot
  FOR EACH ROW
    EXECUTE PROCEDURE xsy.scm_reject_negative_snapshot_mutation();

SET check_function_bodies = true;
