CREATE TABLE xsy.xsy_report_negative_stock_snapshot (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.xsy_report_negative_stock_snapshot_id_seq
                                                       START WITH 1
                                                       INCREMENT BY 1
                                                       NO MINVALUE
                                                       NO MAXVALUE
                                                       CACHE 1),
  snapshot_no varchar(64) NOT NULL,
  warehouse_id bigint NOT NULL,
  warehouse_name varchar(100) NOT NULL,
  snapshot_month date NOT NULL,
  captured_at timestamp with time zone NOT NULL,
  row_count bigint NOT NULL,
  zero_cost_row_count bigint NOT NULL,
  estimated_amount numeric(38, 4) NOT NULL,
  row_data jsonb NOT NULL,
  remark varchar(500),
  created_by varchar(64) NOT NULL,
  CONSTRAINT xsy_report_negative_stock_snapshot_check CHECK (jsonb_array_length(row_data) = row_count),
  CONSTRAINT xsy_report_negative_stock_snapshot_row_count_check CHECK (row_count >= 0),
  CONSTRAINT xsy_report_negative_stock_snapshot_row_data_check CHECK (jsonb_typeof(row_data) = CAST('array' AS text)),
  CONSTRAINT xsy_report_negative_stock_snapshot_snapshot_month_check CHECK (EXTRACT(DAY FROM snapshot_month) = CAST(1 AS numeric)),
  CONSTRAINT xsy_report_negative_stock_snapshot_zero_cost_row_count_check CHECK (zero_cost_row_count >= 0),
  CONSTRAINT xsy_report_negative_stock_snapshot_pkey PRIMARY KEY (id),
  CONSTRAINT xsy_report_negative_stock_snapshot_snapshot_no_key UNIQUE (snapshot_no)
);

