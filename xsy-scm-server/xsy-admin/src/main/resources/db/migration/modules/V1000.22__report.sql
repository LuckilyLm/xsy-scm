CREATE SCHEMA IF NOT EXISTS xsy;
SET search_path TO xsy, public;
SET check_function_bodies = false;

CREATE SEQUENCE xsy.report_negative_stock_snapshot_no_seq
  START WITH 1
  INCREMENT BY 1
  NO MINVALUE
  NO MAXVALUE
  CACHE 1;

CREATE FUNCTION xsy.scm_reject_negative_snapshot_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Negative stock snapshots are append-only';
END;
$$;

