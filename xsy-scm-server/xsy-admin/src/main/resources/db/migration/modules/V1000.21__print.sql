CREATE SCHEMA IF NOT EXISTS xsy;
SET search_path TO xsy, public;
SET check_function_bodies = false;

CREATE FUNCTION xsy.reject_scm_print_record_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'scm_print_record is an immutable snapshot';
END $$;

CREATE TABLE xsy.xsy_print_record (
  id bigint CONSTRAINT scm_print_record_id_not_null NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME xsy.scm_print_record_id_seq
                                                                                               START WITH 1
                                                                                               INCREMENT BY 1
                                                                                               NO MINVALUE
                                                                                               NO MAXVALUE
                                                                                               CACHE 1),
  document_type varchar(32) CONSTRAINT scm_print_record_document_type_not_null NOT NULL,
  business_id bigint CONSTRAINT scm_print_record_business_id_not_null NOT NULL,
  business_no varchar(64),
  template_id bigint CONSTRAINT scm_print_record_template_id_not_null NOT NULL,
  template_code varchar(64) CONSTRAINT scm_print_record_template_code_not_null NOT NULL,
  template_name varchar(100) CONSTRAINT scm_print_record_template_name_not_null NOT NULL,
  template_version integer CONSTRAINT scm_print_record_template_version_not_null NOT NULL,
  model_snapshot jsonb CONSTRAINT scm_print_record_model_snapshot_not_null NOT NULL,
  data_snapshot jsonb CONSTRAINT scm_print_record_data_snapshot_not_null NOT NULL,
  printed_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP CONSTRAINT scm_print_record_printed_at_not_null NOT NULL,
  printed_by varchar(64) CONSTRAINT scm_print_record_printed_by_not_null NOT NULL,
  CONSTRAINT ck_scm_print_record_data CHECK (jsonb_typeof(data_snapshot) = CAST('object' AS text)),
  CONSTRAINT ck_scm_print_record_document_type CHECK (((document_type)::text = ANY ((ARRAY['PURCHASE_ORDER'::character varying, 'DELIVERY_NOTE'::character varying, 'SORTING_TICKET'::character varying, 'SALES_ORDER'::character varying, 'TRACE_UNIT'::character varying, 'STATEMENT'::character varying, 'CUSTOMER_SORTING_SHEET'::character varying, 'CUSTOMER_DELIVERY_NOTE'::character varying])::text[]))),
  CONSTRAINT ck_scm_print_record_model CHECK (jsonb_typeof(model_snapshot) = CAST('object' AS text)),
  CONSTRAINT scm_print_record_pkey PRIMARY KEY (id)
);

