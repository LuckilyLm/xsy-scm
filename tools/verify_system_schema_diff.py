def psql(sql):
    """以 -At -F'\x1f' 执行只读查询并返回行列表。"""
    import os
    env = dict(os.environ)
    cmd = [PSQL, "-h", DB["host"], "-p", DB["port"], "-U", DB["user"],
           "-d", DB["dbname"], "-At", "-F", "\x1f", "-v", "ON_ERROR_STOP=1", "-c", sql]
    out = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", env=env)
    if out.returncode != 0:
        raise SystemExit(f"psql failed:\n{out.stderr}")
    return [l.split("\x1f") for l in out.stdout.splitlines() if l != ""]


