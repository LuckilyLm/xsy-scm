RE_CREATE = re.compile(r'CREATE TABLE "([^"]+)" \((.*?)\n\);', re.S)
RE_INDEX = re.compile(r'CREATE (?:UNIQUE )?INDEX "([^"]+)" ON "([^"]+)" \(([^)]*)\)', re.S)


def parse_c_sql(text):
    tables = {}
    for m in RE_CREATE.finditer(text):
        name, body = m.group(1), m.group(2)
        cols, pk, uniques = [], [], []
        for raw in body.split("\n"):
            line = raw.strip().rstrip(",")
            if not line:
                continue
            if line.upper().startswith("PRIMARY KEY"):
                pk = re.findall(r'"([^"]+)"', line)
                continue
            if line.upper().startswith("CONSTRAINT"):
                cm = re.match(r'CONSTRAINT "([^"]+)" UNIQUE \((.*)\)', line)
                if cm:
                    uniques.append((cm.group(1), re.findall(r'"([^"]+)"', cm.group(2))))
                continue
            cm = re.match(r'"([^"]+)"\s+(.*)$', line)
            if not cm:
                continue
            col, rest = cm.group(1), cm.group(2)
            identity = "GENERATED BY DEFAULT AS IDENTITY" in rest.upper()
            rest_wo_ident = re.sub(r"GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY", "", rest, flags=re.I)
            notnull = bool(re.search(r"\bNOT NULL\b", rest_wo_ident, re.I))
            dm = re.search(r"\bDEFAULT\s+(.+?)(?:\s+(?:NOT NULL|GENERATED)\b|$)", rest_wo_ident, re.I)
            default = dm.group(1).strip() if dm else None
            tm = re.match(r"^([a-zA-Z]+(?:\([^)]*\))?)", rest_wo_ident)
            cols.append(dict(name=col, type=(tm.group(1) if tm else "").lower(),
                             notnull=notnull, default=default, identity=identity))
        # 行内 UNIQUE (col) 形式
        for um in re.finditer(r'(?:^|\n)\s*UNIQUE \((.*?)\)', body):
            uniques.append((None, re.findall(r'"([^"]+)"', um.group(1))))
        tables[name] = dict(columns=cols, pk=sorted(pk),
                            uniques=sorted([sorted(c) for _, c in uniques]), indexes=[])
    for m in RE_INDEX.finditer(text):
        iname, tname, cols = m.group(1), m.group(2), re.findall(r'"([^"]+)"', m.group(3))
        if tname in tables:
            tables[tname]["indexes"].append((iname, sorted(cols)))
    for t in tables.values():
        t["indexes"].sort()
    return tables


# --------------------------------------------------------------------------
# 2. 从 live PG 读取 V2 事实
# --------------------------------------------------------------------------
def read_v2():
    cols = psql(f"""
        SELECT table_name, column_name, data_type,
               COALESCE(character_maximum_length::text,''), is_nullable,
               COALESCE(column_default,''), is_identity
        FROM information_schema.columns
        WHERE table_schema='{DB['schema']}'
        ORDER BY table_name, ordinal_position
    """)
    tables = {}
    for tn, cn, dt, len_, nullable, dflt, ident in cols:
        t = tables.setdefault(tn, dict(columns=[], pk=[], uniques=[], indexes=[]))
        t["columns"].append(dict(name=cn, type=dt + (f"({len_})" if len_ else ""),
                                 notnull=(nullable == "NO"), default=dflt or None,
                                 identity=(ident == "YES")))
    cons = psql(f"""
        SELECT c.relname AS tbl, con.contype, con.conname,
               (SELECT string_agg(a.attname, ',' ORDER BY a.attname)
                  FROM unnest(con.conkey) k JOIN pg_attribute a
                    ON a.attrelid=con.conrelid AND a.attnum=k)
        FROM pg_constraint con JOIN pg_class c ON c.oid=con.conrelid
        JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname='{DB['schema']}' AND con.contype IN ('p','u')
    """)
    for tbl, ctype, cname, colstr in cons:
        if tbl not in tables:
            continue
        c = sorted((colstr or "").split(","))
        if ctype == "p":
            tables[tbl]["pk"] = c
        else:
            tables[tbl]["uniques"].append(c)
    idx = psql(f"""
        SELECT tablename, indexname,
               (SELECT string_agg(a.attname, ',' ORDER BY a.attname)
                  FROM pg_index i JOIN pg_attribute a
                    ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey)
                 WHERE i.indexrelid=pg_class.oid)
        FROM pg_indexes JOIN pg_class ON pg_class.relname=indexname
        WHERE schemaname='{DB['schema']}'
          AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conname=pg_class.relname)
    """)
    for tbl, iname, colstr in idx:
        if tbl in tables:
            tables[tbl]["indexes"].append((iname, sorted((colstr or "").split(","))))
    for t in tables.values():
        t["uniques"].sort()
        t["indexes"].sort()
    return tables


