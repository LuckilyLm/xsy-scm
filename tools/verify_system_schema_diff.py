# 4. 比较
# --------------------------------------------------------------------------
def compare(c_tables, v2_tables):
    report = []
    for tname in sorted(c_tables):
        c = c_tables[tname]
        if tname in DEMO_TABLES:
            report.append(dict(table=tname, verdict="INTENTIONAL_V2_DIFFERENCE",
                               reason="SmartAdmin demo 业务表，W0 已认定不迁（V2 由 product_* 取代）",
                               details=[]))
            continue
        if tname not in v2_tables:
            report.append(dict(table=tname, verdict="POSSIBLE_DEFECT",
                               reason="V2 缺失该表", details=[]))
            continue
        v = v2_tables[tname]
        details = []
        cmap = {c["name"]: c for c in c["columns"]}
        vmap = {c["name"]: c for c in v["columns"]}
        for cn in sorted(set(cmap) | set(vmap)):
            if cn not in vmap:
                details.append(f"column MISSING in V2: {cn} ({cmap[cn]['type']})")
                continue
            if cn not in cmap:
                details.append(f"column EXTRA in V2: {cn} ({vmap[cn]['type']})")
                continue
            a, b = cmap[cn], vmap[cn]
            ta, tb = norm_type(a["type"]), norm_type(b["type"])
            if ta != tb:
                details.append(f"type {cn}: C={a['type']} V2={b['type']}")
            if a["notnull"] != b["notnull"]:
                details.append(f"nullable {cn}: C={'NOT NULL' if a['notnull'] else 'NULL'} "
                               f"V2={'NOT NULL' if b['notnull'] else 'NULL'}")
            # identity 列的隐式默认值不参与比较
            if a["identity"] and b["identity"]:
                pass
            elif a["identity"] != b["identity"]:
                details.append(f"identity {cn}: C={a['identity']} V2={b['identity']}")
            else:
                da = norm_default(a["default"], ta)
                db_ = norm_default(b["default"], tb)
                if da != db_:
                    details.append(f"default {cn}: C={a['default']!r} V2={b['default']!r}")
        if c["pk"] != v["pk"]:
            details.append(f"pk: C={c['pk']} V2={v['pk']}")
        cu, vu = set(map(tuple, c["uniques"])), set(map(tuple, v["uniques"]))
        for x in sorted(cu - vu):
            details.append(f"unique MISSING in V2: {list(x)}")
        for x in sorted(vu - cu):
            details.append(f"unique EXTRA in V2: {list(x)}")
        ci = {(n, tuple(cs)) for n, cs in c["indexes"]}
        vi = {(n, tuple(cs)) for n, cs in v["indexes"]}
        for x in sorted(ci - vi):
            # 索引名在 PG 内全局唯一，C 侧重名时被改名为 表名_原名，需按列组合比对
            if not any(cols == x[1] for _, cols in vi):
                details.append(f"index MISSING in V2: {x[0]}{list(x[1])}")
        for x in sorted(vi - ci):
            if not any(cols == x[1] for _, cols in ci):
                details.append(f"index EXTRA in V2: {x[0]}{list(x[1])}")

        verdict = "SAME" if not details else "POSSIBLE_DEFECT"
        reason = "" if verdict == "SAME" else "见 details"
        if verdict == "POSSIBLE_DEFECT" and tname in ADJUDICATED_INTENTIONAL:
            adj_reason, allowed = ADJUDICATED_INTENTIONAL[tname]
            if all(any(a in d for a in allowed) for d in details):
                verdict = "INTENTIONAL_V2_DIFFERENCE"
                reason = adj_reason
        report.append(dict(table=tname, verdict=verdict, reason=reason, details=details))
    return report


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json")
    args = ap.parse_args()

    text = C_SQL.read_text(encoding="utf-8")
    c_tables = parse_c_sql(text)
    v2_tables = read_v2()

    report = compare(c_tables, v2_tables)
    order = {"POSSIBLE_DEFECT": 0, "INTENTIONAL_V2_DIFFERENCE": 1, "SAME": 2}
    report.sort(key=lambda r: (order[r["verdict"]], r["table"]))

    n_defect = sum(1 for r in report if r["verdict"] == "POSSIBLE_DEFECT")
    n_intent = sum(1 for r in report if r["verdict"] == "INTENTIONAL_V2_DIFFERENCE")
    n_same = sum(1 for r in report if r["verdict"] == "SAME")

    print(f"C 参考表数 = {len(c_tables)}   V2 实测 t_* 表数 = "
          f"{len([t for t in v2_tables if t.startswith('t_')])}")
    print(f"SAME={n_same}  INTENTIONAL_V2_DIFFERENCE={n_intent}  POSSIBLE_DEFECT={n_defect}")
    print("-" * 72)
    for r in report:
        if r["verdict"] == "SAME":
            continue
        print(f"[{r['verdict']}] {r['table']}")
        if r["reason"]:
            print(f"    reason: {r['reason']}")
        for d in r["details"][:40]:
            print(f"    - {d}")
        if len(r["details"]) > 40:
            print(f"    ... ({len(r['details'])} total)")
    print("-" * 72)
    print("SAME 表: " + ", ".join(r["table"] for r in report if r["verdict"] == "SAME"))

    if args.json:
        Path(args.json).write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"\nJSON -> {args.json}")

    return 1 if n_defect else 0


if __name__ == "__main__":
    sys.exit(main())
