# 3. 类型归一
# --------------------------------------------------------------------------
def norm_type(t):
    """把两种合法取舍归一，避免把有意的 BOOLEAN 取舍误报为差异。

    C  : tinyint / tinyint(1) -> SMALLINT
    V2 : tinyint(1) 0/1       -> BOOLEAN ; 其他 tinyint -> SMALLINT
    两者都正确，故统一归到同一"类型族"。
    """
    t = re.sub(r"\s+", " ", t.lower().strip())
    if t in ("smallint", "int2", "boolean", "bool"):
        return "BOOL_OR_SMALLINT"
    if t in ("timestamp without time zone", "timestamp"):
        return "TIMESTAMP"
    if t in ("character varying", "varchar"):
        return "VARCHAR"
    if t.startswith("character varying(") or t.startswith("varchar("):
        return "VARCHAR" + t[t.index("("):]
    return t


RE_NULL_CAST = re.compile(r"^NULL::[a-z ]+(\(\d+\))?$", re.I)
RE_STR_CAST = re.compile(r"^(.*?)::(character varying|text|varchar)(\(\d+\))?$", re.I)


def norm_default(d, coltype):
    """归一默认值写法：NULL / 'x'::type / 0|false / CURRENT_TIMESTAMP|now()。"""
    if d is None:
        return None
    s = d.strip()
    if s == "" or RE_NULL_CAST.match(s) or s.upper() == "NULL":
        return None
    m = RE_STR_CAST.match(s)
    if m:
        s = m.group(1).strip()
    if re.fullmatch(r"CURRENT_TIMESTAMP|now\(\)|NOW", s, re.I):
        return "NOW"
    s = s.strip()
    if s.startswith("'") and s.endswith("'"):
        inner = s[1:-1].replace("''", "'")
        # BOOLEAN 族：'0'/'1' 与 false/true 等价
        if coltype == "BOOL_OR_SMALLINT" and inner in ("0", "1"):
            return inner
        return inner
    if s.lower() in ("true", "false"):
        if coltype == "BOOL_OR_SMALLINT":
            return "1" if s.lower() == "true" else "0"
        return s.lower()
    if re.fullmatch(r"0\.0+", s):
        return "0"
    return s


