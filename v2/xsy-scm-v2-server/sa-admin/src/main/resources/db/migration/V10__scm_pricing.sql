-- W3 approved Pricing aggregate. Immutable after first successful Flyway application.
-- PostgreSQL only. No foreign keys; parent row locks protect price periods.

CREATE TABLE customer_agreement_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    unit_price NUMERIC(18,4) NOT NULL,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64), updated_by VARCHAR(64),
    CONSTRAINT ck_customer_agreement_price_amount CHECK (unit_price >= 0),
    CONSTRAINT ck_customer_agreement_price_period CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT ck_customer_agreement_price_version CHECK (version >= 0)
);
CREATE INDEX idx_customer_agreement_price_lookup ON customer_agreement_price (customer_id,sku_id,effective_from,effective_to) WHERE deleted=FALSE;
CREATE INDEX idx_customer_agreement_price_effective ON customer_agreement_price (effective_from DESC,id DESC) WHERE deleted=FALSE;
CREATE INDEX idx_customer_agreement_price_sku_id ON customer_agreement_price (sku_id) WHERE deleted=FALSE;

