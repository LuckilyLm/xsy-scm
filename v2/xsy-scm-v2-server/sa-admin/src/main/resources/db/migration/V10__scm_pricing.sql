);
CREATE UNIQUE INDEX uk_customer_sku_visibility_active ON customer_sku_visibility (customer_id,sku_id) WHERE deleted=FALSE;
CREATE INDEX idx_customer_sku_visibility_sku_id ON customer_sku_visibility (sku_id);
