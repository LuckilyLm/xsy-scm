CREATE TABLE customer_price_batch_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_key VARCHAR(100) NOT NULL,
    operation_type VARCHAR(32) NOT NULL,
    result VARCHAR(16) NOT NULL,
    row_count INTEGER NOT NULL,
    error_data JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    CONSTRAINT ck_customer_price_batch_result CHECK (result IN ('SUCCESS','FAILED'))
);
CREATE INDEX idx_customer_price_batch_audit_key ON customer_price_batch_audit (batch_key,created_at DESC);
CREATE UNIQUE INDEX uk_customer_price_batch_audit_success ON customer_price_batch_audit (batch_key) WHERE result='SUCCESS';

